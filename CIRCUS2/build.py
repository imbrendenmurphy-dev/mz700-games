def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96 + 0x80
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c
    return t


def codes(s):
    t = atod()
    return [t[ord(c)] for c in s]


