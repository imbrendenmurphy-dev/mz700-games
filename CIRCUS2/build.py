def big_cells(ch):
    rows = BIG.get(ch, BIG[' '])

    def px(x, y):
        return 1 if x < 3 and y < 5 and rows[y][x] == '#' else 0
    out = []
    for cr in range(3):
        for cc in range(2):
            x, y = 2 * cc, 2 * cr
            out.append(0xF0 | px(x, y) | px(x + 1, y) << 1 | px(x, y + 1) << 2 | px(x + 1, y + 1) << 3)
    return out


# ---------------------------------------------------------------- tables
def gen_tables():
    out = ['; generated by build.py', '        align 256', 'ATOD:', db_lines(atod()),
           '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    out += ['        align 256', 'ROWTAB:', dw_lines(['BGC+%d' % (r * 40) for r in range(25)])]
    sin = [round(127 * math.sin(2 * math.pi * i / 64)) for i in range(64)]
    out += ['SINTAB:', db_lines(sin)]
    pops = [round(music.CLOCK / (650 * 1.13 ** k)) for k in range(9)]
    out += ['POPDIV:', dw_lines(pops)]
    big = []
    for c in range(32, 91):
        big += big_cells(chr(c))
    out += ['BIGFONT_N equ 59', 'BIGFONT:', db_lines(big, 12)]
    return NL.join(out) + NL


