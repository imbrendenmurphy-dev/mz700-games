FACE_COL = 19
TMSG_ROW = 23
SKY = BLUE


def title_art():
    ch = [[0] * 40 for _ in range(25)]
    at = [[SKY] * 40 for _ in range(25)]

    def put(r, c, g, fg, bg, bank=0):
        ch[r][c] = g
        at[r][c] = (bank << 7) | (fg << 4) | bg
    # logo
    word = 'CIRCUS 2'
    cols = []
    letter_of = [255] * 40
    for li, L in enumerate(word):
        w = len(LETTERS[L][0])
        cols.append((L, li, w))
    width = sum(w for _, _, w in cols) + len(cols) - 1
    x = (40 - width) // 2
    for L, li, w in cols:
        for y in range(LOGO_H):
            for dx in range(w):
                g = LCH[LETTERS[L][y][dx]]
                if g:
                    put(LOGO_ROW + y, x + dx, g, YELLOW, SKY)
                    letter_of[x + dx] = li
        x += w + 1
    # the big top: roof rows 7..12
    spans = [(19, 20), (17, 22), (14, 25), (12, 27), (9, 30), (6, 33)]
    for k, (c0, c1) in enumerate(spans):
        r = 7 + k
        for c in range(c0, c1 + 1):
            stripe = RED if ((c - 4) // 2) % 2 == 0 else WHITE
            if c == c0:
                put(r, c, 0x4E, stripe, SKY)
            elif c == c1:
                put(r, c, 0x4D, stripe, SKY)
            else:
                put(r, c, 0x43, stripe, SKY)
    put(6, 19, 0x75, WHITE, SKY)                  # the flag pole
    put(6, 20, 0x56, RED, SKY)                    # pennant
    # the valance with its bulbs (row 13) and the scallops below
    for c in range(6, 34):
        put(MARQ_ROW, c, 0x47 if c % 2 == 0 else 0, YELLOW, RED)
    for c in range(7, 33):
        put(14, c, 0x42 if c % 2 else 0x56, RED, YELLOW if ((c - 7) // 2) % 2 else WHITE)
    # the tent's body rows 15..21, columns 7..32
    for r in range(15, 22):
        for c in range(7, 33):
            stripe = YELLOW if ((c - 7) // 2) % 2 else WHITE
            put(r, c, 0x75 if c % 2 else 0, RED, stripe)
    # the door: rows 16..21, columns 17..22, curtains tied back
    for r in range(16, 22):
        for c in range(17, 23):
            put(r, c, 0, WHITE, BLACK)
    for r in range(16, 22):                       # curtains tied back
        put(r, 17, 0x43, RED, BLACK)
        put(r, 22, 0x43, RED, BLACK)
    put(16, 18, 0x56, RED, BLACK)
    put(17, 18, 0x56, RED, BLACK)
    put(16, 21, 0x42, RED, BLACK)
    put(17, 21, 0x42, RED, BLACK)
    put(19, 18, 0x4E, RED, BLACK)
    put(19, 21, 0x4D, RED, BLACK)
    put(20, 18, 0x43, RED, BLACK)
    put(20, 21, 0x43, RED, BLACK)
    put(21, 18, 0x43, RED, BLACK)
    put(21, 21, 0x43, RED, BLACK)
    put(FACE_ROW - 1, FACE_COL, 0x41, RED, BLACK)            # hat
    put(FACE_ROW, FACE_COL, 0xCE, YELLOW, BLACK)             # face
    put(FACE_ROW + 1, FACE_COL, 0x44, WHITE, BLACK, 1)       # body
    put(FACE_ROW - 1, FACE_COL + 1, 0x47, RED, BLACK)        # a balloon he holds
    put(FACE_ROW, FACE_COL + 1, 0x35, WHITE, BLACK)
    # ground and the bottom lines
    for c in range(40):
        put(22, c, 0x7A, GREEN, BLACK)
        put(23, c, 0, WHITE, BLACK)
        put(24, c, 0, WHITE, BLACK)
    line = 'A VZ300 CLASSIC FOR THE SHARP MZ-700'
    x = (40 - len(line)) // 2
    for i, cc in enumerate(codes(line)):
        put(24, x + i, cc, CYAN, BLACK)
    # stars in the sky
    rnd = random.Random(7)
    stars = []
    while len(stars) < 18:
        r = rnd.randrange(0, 12)
        c = rnd.randrange(1, 39)
        if ch[r][c] or at[r][c] != SKY or (r, c) in stars:
            continue
        if 6 <= r and 4 <= c <= 35:
            continue
        if LOGO_ROW - 1 <= r <= LOGO_ROW + LOGO_H and any(ch[rr][cc] for rr in range(LOGO_ROW, LOGO_ROW + LOGO_H)
                                                           for cc in range(c - 1, c + 2) if 0 <= cc < 40):
            continue
        stars.append((r, c))
        put(r, c, 0x2E, YELLOW, SKY)
    flat_c = [v for row in ch for v in row]
    flat_a = [v for row in at for v in row]
    return flat_c, flat_a, letter_of, stars


def rle(chars, attrs):
    out = []
    i = 0
    while i < len(chars):
        n = 1
        while i + n < len(chars) and n < 255 and chars[i + n] == chars[i] and attrs[i + n] == attrs[i]:
            n += 1
        out += [n, chars[i], attrs[i]]
        i += n
    return out + [0]


def gen_art():
    c, a, letter_of, stars = title_art()
    data = rle(c, a)
    out = ['; generated by build.py - the title picture',
           'LOGO_ROW equ %d' % LOGO_ROW, 'LOGO_H equ %d' % LOGO_H,
           'MARQ_ROW equ %d' % MARQ_ROW, 'MARQ_C0 equ %d' % MARQ_C0, 'MARQ_C1 equ %d' % MARQ_C1,
           'MARQ_BG equ %d' % RED, 'FACE_ROW equ %d' % FACE_ROW, 'FACE_COL equ %d' % FACE_COL,
           'TMSG_ROW equ %d' % TMSG_ROW, 'NSTARS equ %d' % len(stars),
           'TITLE_ART:', db_lines(data),
           'LOGO_LETTER:', db_lines(letter_of),
           'LOGO_COLS: db %d,%d,%d,%d,%d,%d,%d,%d' % ((RED << 4), (YELLOW << 4), (WHITE << 4), (CYAN << 4),
                                                     (MAGENTA << 4), (GREEN << 4), (YELLOW << 4), (WHITE << 4)),
           'STARS:', db_lines([v for rc in stars for v in rc])]
    return NL.join(out) + NL, len(data), (c, a)


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    write('gen_tables.inc', gen_tables())
    acts, totals = gen_acts()
    write('gen_acts.inc', acts)
    write('gen_music.inc', music.gen_asm())
    art, artlen, _ = gen_art()
    write('gen_art.inc', art)
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/circus2.sym',
                        '--lst=../build/circus2.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'circus2.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: binary %d bytes (%04X-%04X), title art %d bytes packed' % (
        NAME, len(data), LOAD, LOAD + len(data) - 1, artlen))
    print('balloons per act:', totals)


if __name__ == '__main__':
    main()
