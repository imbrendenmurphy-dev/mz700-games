def db_lines(vals, per=16):
    return NL.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                   for i in range(0, len(vals), per))


def dw_lines(vals, per=8):
    return NL.join('        dw ' + ','.join('%s' % v for v in vals[i:i + per])
                   for i in range(0, len(vals), per))


