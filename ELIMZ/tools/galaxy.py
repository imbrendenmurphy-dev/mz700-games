"""galaxy.py - the STARHAUL galaxy: 256 star systems, generated at build time.

Original design: names are built from our own syllable list, positions are
scattered with a minimum spacing and then nudged until every system can be
reached from every other with a full tank (7.0 light years).

Distances use the same octagonal approximation as the Z80 code:
    d = max(dx, dy) + min(dx, dy) / 2      (galaxy units, 1 unit = 0.4 ly)
"""
import random

N = 256
GW, GH = 256, 116                 # galaxy units
MAXFUEL = 70                      # tenths of a light year
RANGE_UNITS = MAXFUEL // 4        # 1 unit = 0.4 ly = 4 tenths

SYL = ['KOR', 'VEN', 'AL', 'TRI', 'SA', 'MOR', 'DEX', 'UL', 'PHA', 'RI', 'ON', 'BEL', 'QUA', 'ZI',
       'NOR', 'ETH', 'CA', 'LU', 'SOL', 'VAR', 'IN', 'TAR', 'GO', 'ME', 'RHO', 'KA', 'VEX', 'OS',
       'DRA', 'YL', 'BRI', 'TO']

ECON = ['FARMWORLD', 'FARMWORLD', 'PASTORAL', 'MIXED', 'MIXED', 'MANUFACTURING', 'INDUSTRIAL',
        'HEAVY INDUSTRY']
GOV = ['LAWLESS', 'WARLORDS', 'CLANS', 'MONARCHY', 'REPUBLIC', 'COUNCIL', 'FEDERATION',
       'TECHNOCRACY']


def dist(a, b):
    dx, dy = abs(a[0] - b[0]), abs(a[1] - b[1])
    return max(dx, dy) + min(dx, dy) // 2


def components(pos):
    seen = [-1] * len(pos)
    comp = 0
    for s in range(len(pos)):
        if seen[s] >= 0:
            continue
        stack = [s]
        seen[s] = comp
        while stack:
            i = stack.pop()
            for j in range(len(pos)):
                if seen[j] < 0 and dist(pos[i], pos[j]) <= RANGE_UNITS:
                    seen[j] = comp
                    stack.append(j)
        comp += 1
    return seen, comp


def make(seed=1866):
    rng = random.Random(seed)
    pos = []
    while len(pos) < N:
        p = (rng.randrange(4, GW - 4), rng.randrange(4, GH - 4))
        if all(dist(p, q) >= 5 for q in pos):
            pos.append(p)
    # join every island to the main cluster
    while True:
        seen, n = components(pos)
        if n == 1:
            break
        sizes = [seen.count(c) for c in range(n)]
        main = sizes.index(max(sizes))
        lone = next(i for i in range(N) if seen[i] != main)
        anchors = [i for i in range(N) if seen[i] == main]
        a = pos[min(anchors, key=lambda k: dist(pos[k], pos[lone]))]
        for _ in range(200):
            p = (min(GW - 4, max(4, a[0] + rng.randrange(-12, 13))), min(GH - 4, max(4, a[1] + rng.randrange(-12, 13))))
            if dist(p, a) <= RANGE_UNITS - 2 and all(dist(p, q) >= 4 for k, q in enumerate(pos) if k != lone):
                pos[lone] = p
                break
    names = set()
    systems = []
    for i in range(N):
        while True:
            k = 2 if rng.random() < 0.6 else 3
            nm = ''.join(rng.choice(SYL) for _ in range(k))
            if nm not in names and len(nm) <= 9:
                break
        names.add(nm)
        econ = rng.randrange(8)
        gov = rng.randrange(8)
        tech = max(1, min(15, 2 + econ + rng.randrange(-2, 6) + gov // 3))
        systems.append(dict(x=pos[i][0], y=pos[i][1], name=nm, econ=econ, gov=gov, tech=tech))
    # start: a peaceful mixed world near the middle
    cx, cy = GW // 2, GH // 2
    start = min(range(N), key=lambda i: dist(pos[i], (cx, cy)) + (0 if systems[i]['gov'] >= 4 else 40))
    return systems, start


# each system's look: the planet's colour (bits 0-2), its star's (bits
# 4-6) and which of four coronas the star has (bits 3 and 7), as MZ-700
# colour numbers: sixteen star and corona pairs in all.  Farm worlds lean green, industry
# worlds yellow and red; stars are mostly yellow, some white, red or blue.
RED, MAGENTA, GREEN, CYAN, YELLOW, WHITE = 2, 3, 4, 5, 6, 7


def looks(systems, start):
    rng = random.Random(4242)
    out = []
    for i, s in enumerate(systems):
        farm = s['econ'] <= 2                     # farm or pastoral
        pl = rng.choice([GREEN, GREEN, CYAN, CYAN, MAGENTA, WHITE] if farm else
                        [YELLOW, RED, MAGENTA, CYAN, WHITE, GREEN])
        star = rng.choice([YELLOW] * 5 + [WHITE] * 2 + [RED] * 2 + [CYAN])
        var = rng.randrange(4)                  # which corona (bits 3, 7)
        if i == start:
            pl, star, var = CYAN, YELLOW, 0
        out.append(pl | star << 4 | (var & 1) << 3 | (var >> 1) << 7)
    return out


def gen_asm(db_lines):
    systems, start = make()
    nl = chr(10)
    out = ['; generated by tools/galaxy.py - 256 star systems',
           'NSYS equ %d' % N, 'START_SYS equ %d' % start, 'MAXFUEL equ %d' % MAXFUEL,
           'DEMO_SYS equ %d' % min((i for i in range(N) if systems[i]['gov'] == 0),
                                   key=lambda i: dist((systems[i]['x'], systems[i]['y']), (128, 58))),
           '        align 256']
    for lab, key in (('SYS_GX', 'x'), ('SYS_GY', 'y'), ('SYS_ECON', 'econ'), ('SYS_GOV', 'gov'),
                     ('SYS_TECH', 'tech')):
        out += ['%s:' % lab, db_lines([s[key] for s in systems])]
    out += ['SYS_LOOK:', db_lines(looks(systems, start))]
    out += ['SYS_CX:', db_lines([s['x'] * 5 // 16 for s in systems]),
            'SYS_CY:', db_lines([s['y'] * 5 // 16 for s in systems])]
    names = []
    for s in systems:
        b = [ord(c) for c in s['name']]
        names += b + [0] * (10 - len(b))
    out += ['SYS_NAME:', db_lines(names, 20)]
    for lab, tab in (('ECON_NAMES', ECON), ('GOV_NAMES', GOV)):
        out.append('%s:' % lab)
        for t in tab:
            out.append('        db "%s",0' % t)
    return nl.join(out) + nl, systems, start


if __name__ == '__main__':
    systems, start = make()
    seen, n = components([(s['x'], s['y']) for s in systems])
    print('components', n, 'start', start, systems[start])
    reach = [sum(1 for t in systems if t is not s and dist((s['x'], s['y']), (t['x'], t['y'])) <= RANGE_UNITS)
             for s in systems]
    print('neighbours in range: min %d max %d mean %.1f' % (min(reach), max(reach), sum(reach) / N))
    print([s['name'] for s in systems[:20]])
