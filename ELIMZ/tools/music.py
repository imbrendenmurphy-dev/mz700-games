"""music.py - songs and sound effects for STARHAUL (one 8253 square voice).

Same tracker format and player as the other MZ-700 games (src/sound.asm):
each row lasts `speed` fields and holds a lead note, a bass note, a drum
and an effect byte.

The waltz is an original arrangement of Johann Strauss II's "An der
schoenen blauen Donau" (1866, public domain): the opening waltz theme
with an oom-pah-pah bass.
"""
CLOCK = 1108800
NOTE_BASE = 20                      # NOTETAB index = midi - NOTE_BASE

NAMES = {'C': 0, 'C#': 1, 'DB': 1, 'D': 2, 'D#': 3, 'EB': 3, 'E': 4, 'F': 5, 'F#': 6, 'GB': 6,
         'G': 7, 'G#': 8, 'AB': 8, 'A': 9, 'A#': 10, 'BB': 10, 'B': 11}


def midi(tok):
    tok = tok.upper()
    n, o = tok[:-1], int(tok[-1])
    return NAMES[n] + 12 * (o + 1)


def notetab():
    vals = []
    for i in range(128):
        m = i + NOTE_BASE
        f = 440.0 * 2 ** ((m - 69) / 12)
        d = round(CLOCK / f)
        vals.append(max(2, min(65535, d)))
    vals[0] = 0
    return vals


def note_byte(tok):
    if tok == '-':
        return 0
    if tok == '.':
        return 1
    idx = midi(tok) - NOTE_BASE
    assert 1 <= idx < 127, tok
    return idx + 1


DRUM = {'.': 0, 'k': 1, 's': 2, 'h': 3}


def pattern_rows(L, B, D, F):
    n = len(L)
    assert len(B) == n and len(D) == n and len(F) == n, (len(L), len(B), len(D), len(F))
    out = []
    for i in range(n):
        out += [note_byte(L[i]), note_byte(B[i]), DRUM[D[i]], F[i]]
    return out + [0xFF]


# ------------------------------------------------------------------ the waltz
# One bar = 3 beats = 6 rows.  A bar is written as three beat tokens:
# a note, '.' (silence) or '-' (hold).  Each phrase is 4 bars + a chord list.
WALTZ = [
    ('D4 D4 F#4  A4 - -  . A5 A5  . F#5 F#5', 'D D D D'),
    ('D4 D4 F#4  A4 - -  . A5 A5  . G5 G5', 'D D A A'),
    ('C#4 C#4 E4  B4 - -  . B5 B5  . G5 G5', 'A A A A'),
    ('C#4 C#4 E4  B4 - -  . B5 B5  . F#5 F#5', 'A A D D'),
    ('D4 D4 F#4  A4 D5 -  . D6 D6  . A5 A5', 'D D D D'),
    ('D4 D4 F#4  A4 D5 -  . D6 D6  . B5 B5', 'D D G G'),
    ('E4 E4 G4  B4 - -  G#4 A4 -  F#5 - -', 'E E D D'),
    ('D5 F#4 -  F#4 E4 B4  A4 - -  D4 . .', 'D A A D'),
]
# chord -> (root, fifth-ish second note) for the oom-pah-pah
CHORD = {'D': ('D3', 'A3'), 'A': ('A2', 'E3'), 'G': ('G2', 'D3'), 'E': ('E3', 'B3')}


def waltz_song():
    pats = []
    for mel, chords in WALTZ:
        beats = mel.split()
        assert len(beats) == 12, mel
        lead = []
        for b in beats:
            lead += [b, '-']                 # a beat = 2 rows
        bass = []
        drums = []
        for c in chords.split():
            root, fifth = CHORD[c]
            bass += [root, '-', fifth, '-', fifth, '-']
            drums += list('..h.h.')
        fx = [0] * len(lead)
        run = 0
        for k, t in enumerate(lead):          # octave shimmer on long notes
            run = run + 1 if t == '-' else 0
            if run >= 3:
                fx[k] = 3
        pats.append(pattern_rows(lead, bass, drums, fx))
    return dict(speed=7, pats=pats, loop=True)


def jingle(notes, bass, speed):
    lead = notes.split() + ['.']
    b = (bass.split() + ['-'] * len(lead))[:len(lead) - 1] + ['.']
    n = len(lead)
    return dict(speed=speed, pats=[pattern_rows(lead, b, ['.'] * n, [0] * n)], loop=False)


SONGS = {}


def build_songs():
    SONGS['SONG_WALTZ'] = waltz_song()
    SONGS['SONG_OVER'] = jingle('A4 - G4 - F4 - E4 - - - D4 - - - - -', 'D3 - C3 - A#2 - A2 - - - D2', 6)


# ------------------------------------------------------------------ effects (one word per 50 Hz tick)
REST = 0xFE00


def div(f):
    return max(2, min(0xFDFF, round(CLOCK / f)))


def noise(band):
    return 0xFF00 | band


def sweep(f0, f1, ticks):
    return [div(f0 * (f1 / f0) ** (i / max(1, ticks - 1))) for i in range(ticks)]


SFX = {
    'SFX_LASER': sweep(2400, 700, 4),
    'SFX_HIT': [noise(0), div(1500), noise(1)],
    'SFX_BOOM': [noise(n) for n in (0, 1, 2, 3, 4, 5, 6, 8, 10, 12, 14, 16, 20, 24)],
    'SFX_OUCH': [noise(2), div(200), noise(4), div(150), noise(6)],
    'SFX_ZAP': sweep(900, 300, 5),
    'SFX_DOCK': [div(f) for f in (523, 523, 659, 659, 784, 784, 1047, 1047, 1047)],
    'SFX_BEEP': [div(1200), div(1200)],
    'SFX_SCOOP': [div(f) for f in (660, 660, 880, 880, 1320, 1320)],
    'SFX_ALARM': [div(f) for f in (900, 900, 600, 600) * 4],
    'SFX_WARN': [div(1800), div(1800), 0xFE00, div(1800), div(1800)],
    'SFX_LAUNCH': [noise(1), noise(2)] + sweep(300, 1400, 8),
    'SFX_JUMP': sweep(150, 3000, 30) + sweep(3000, 200, 20),
    'SFX_CRASH': [noise(n) for n in (4, 6, 8, 10, 12, 14, 16, 20, 24, 28, 32)],
}


def gen_asm():
    build_songs()
    out = ['; generated by tools/music.py']
    for name, s in SONGS.items():
        out.append('%s:' % name)
        out.append('        db %d' % s['speed'])
        names = ['%s_p%d' % (name, i) for i in range(len(s['pats']))]
        out.append('        dw ' + ','.join(names))
        out.append('        dw %d' % (0 if s['loop'] else 1))
        for n, p in zip(names, s['pats']):
            out.append('%s:' % n)
            for i in range(0, len(p), 16):
                out.append('        db ' + ','.join('%d' % v for v in p[i:i + 16]))
    for name, words in SFX.items():
        out.append('%s:' % name)
        out.append('        dw ' + ','.join('%d' % w for w in words) + ',0')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    print(gen_asm()[:400])
