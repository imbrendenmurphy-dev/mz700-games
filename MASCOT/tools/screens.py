def pic_bytes(pic):
    h, w = len(pic), len(pic[0])
    out = [w, h]
    for row in pic:
        for c in row:
            if c is None:
                out += [0, 0]
            else:
                g, fg, bg = c
                out += [g & 0xFF, ((g >> 8) << 7) | (fg << 4) | (8 if bg == ca.TR else bg)]
    return out


def db(vals):
    return '\n'.join('        db ' + ','.join('%d' % v for v in vals[i:i + 20]) for i in range(0, len(vals), 20))


def gen_asm():
    out = ['; generated by tools/screens.py']
    lg = logo()
    out.append('LOGO_W equ %d' % len(lg[0]))
    for name, pic in (('PIC_LOGO', lg), ('PIC_BIGKIKO', ca.parse(BIGKIKO)),
                      ('PIC_PRISM', ca.parse(PRISM_BIG)), ('PIC_BARON', ca.parse(BARON_BIG))):
        out.append('%s:' % name)
        out.append(db(pic_bytes(pic)))
    return '\n'.join(out) + '\n'


