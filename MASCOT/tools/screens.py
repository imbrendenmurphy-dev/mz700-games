"""screens.py - front-end pictures: the KIKO logo, big Kiko, prisms, Baron.

Pictures are cell art (celart.py tokens) emitted as  db w, h, then (ch, at)
pairs; attribute bit 3 = keep the screen's background colour.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import celart as ca  # noqa: E402

# ------------------------------------------------------------------ logo
# block letters, 5 wide x 6 tall:  # block  / lower-right  \ lower-left
# L upper-right  J upper-left  (triangles)  . empty
LETTERS = {
    'K': ['##../#', '##./#J', '##/#J.', '###\\..', '##L#\\.', '##.L#\\'],
    'I': ['####', '.##.', '.##.', '.##.', '.##.', '####'],
    'O': ['/###\\', '##.##', '##.##', '##.##', '##.##', 'L###J'],
}
LCH = {'#': 0x043, '.': None, '/': 0x04E, '\\': 0x04D, 'L': 0x042, 'J': 0x056}
WORD = 'KIKO'


def logo():
    rows = [[] for _ in range(6)]
    for i, ch in enumerate(WORD):
        for y in range(6):
            for c in LETTERS[ch][y]:
                g = LCH[c]
                rows[y].append(None if g is None else (g, 4, ca.TR))
            if i < len(WORD) - 1:
                rows[y].append(None)
    return rows


