"""build.py - builds KIKO for the Sharp MZ-700.

    py build.py            generate data, assemble, write build/ and release/
    py build.py preview    also draw every room to build/rooms/*.png

Generates build/gen_*.inc from the Python data in tools/, assembles
src/main.asm with sjasmplus and writes build/KIKO.MZT (emulators) plus an
identical KIKO.MZF (UniCMT / real hardware); both are copied to release/.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(ROOT, 'tools')
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
REL = os.path.join(ROOT, 'release')
sys.path.insert(0, TOOLS)

import tiles as TL  # noqa: E402
import sprites as SP  # noqa: E402
import rooms as RM  # noqa: E402
import levels as LV  # noqa: E402
import music  # noqa: E402
import screens  # noqa: E402

NAME = 'KIKO'
LOAD = 0x1200


def db_lines(vals, per=16):
    return '\n'.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


def ident(s):
    return ''.join(c if c.isalnum() else '_' for c in s)


# ---------------------------------------------------------------- tiles
def gen_tiles():
    ch, at, fl, an = TL.tables()
    out = ['; generated by build.py - tile tables', '        align 256', 'TCHR:', db_lines(ch),
           'TATR:', db_lines(at), 'TFLG:', db_lines(fl), 'TANIM:', db_lines(an)]
    for k, v in (('F_SOLID', TL.F_SOLID), ('F_ONEWAY', TL.F_ONEWAY), ('F_HURT', TL.F_HURT),
                 ('F_VINE', TL.F_VINE), ('F_GEM', TL.F_GEM), ('F_ITEM', TL.F_ITEM),
                 ('F_SPRING', TL.F_SPRING), ('F_CRUMBLE', TL.F_CRUMBLE)):
        out.append('%s equ %d' % (k, v))
    for i, t in enumerate(TL.TILES):
        out.append('T_%s equ %d' % (ident(t.name), i))
    # per-world table: sky tile, chroma base, sky colour, spring, spring_c,
    # crumble, crack, apple, oneup, golden, golden2, plat attr
    out.append('WORLDTAB:')
    for w in TL.WORLDS:
        sky = TL.CL[TL.SKY[w]]
        plat = {'W1': ('Y', 'B'), 'W2': ('M', 'K'), 'W3': ('M', 'C'), 'W4': ('W', 'K')}[w]
        vals = [TL.tid(w, 'sky'), TL.CHROMA_BASE[w], sky, TL.tid(w, 'spring'), TL.tid(w, 'spring_c'),
                TL.tid(w, 'crumble'), TL.tid(w, 'crack'), TL.tid(w, 'apple'), TL.tid(w, 'oneup'),
                TL.tid(w, 'golden'), TL.tid(w, 'golden2'), TL.CL[plat[0]],
                TL.tid(w, 'gem0'), 0, 0, 0]
        out.append(db_lines(vals))
    out += ['WT_SKY equ 0', 'WT_CHROMA equ 1', 'WT_SKYCOL equ 2', 'WT_SPRING equ 3',
            'WT_SPRINGC equ 4', 'WT_CRUMBLE equ 5', 'WT_CRACK equ 6', 'WT_APPLE equ 7',
            'WT_ONEUP equ 8', 'WT_GOLDEN equ 9', 'WT_GOLDEN2 equ 10', 'WT_PLATCOL equ 11', 'WT_GEM0 equ 12']
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- remap tables
def gen_remap():
    """REMAP+c*256: attribute with green (4) replaced by colour c, in fg and
    in an opaque bg.  REMAPW: everything white (hit flash)."""
    out = ['; generated by build.py - sprite recolour tables', '        align 256', 'REMAP:']
    for c in range(8):
        t = []
        for a in range(256):
            fg, bg = (a >> 4) & 7, a & 7
            if fg == 4:
                fg = c
            if not (a & 8) and bg == 4:
                bg = c
            t.append((a & 0x88) | (fg << 4) | bg)
        out.append(db_lines(t))
    t = []
    for a in range(256):
        bg = a & 7 if a & 8 else 7
        t.append((a & 0x88) | 0x70 | bg)
    out.append('REMAPW:')
    out.append(db_lines(t))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- sprites
def gen_sprites():
    out = ['; generated by build.py - sprite frames (w, h, ox, oy, then ch/at pairs)']
    total = 0
    for name, b in SP.all_frames():
        out.append('FR_%s:' % name)
        out.append(db_lines(b))
        total += len(b)
    return '\n'.join(out) + '\n', total


# ---------------------------------------------------------------- rooms
def gen_rooms():
    out = ['; generated by build.py - rooms and levels']
    rooms = []
    for lv in LV.LEVELS:
        for r in lv.rooms:
            r.index = len(rooms)
            rooms.append(r)
        lv.link()
    assert len(rooms) < 255
    out.append('NROOMS equ %d' % len(rooms))
    out.append('NLEVELS equ %d' % len(LV.LEVELS))
    out.append('ROOMTAB:')
    out.append('        dw ' + ','.join('room_%d' % i for i in range(len(rooms))))
    total = 0
    for lv in LV.LEVELS:
        base = 0
        for r in lv.rooms:
            r.gem_base = base
            base += len(r.gems())
        lv.ngems = sum(1 for r in lv.rooms for (x, y) in r.gems()
                       if TL.TILES[r.T[y][x]].flags & TL.F_GEM)
        assert base <= 256, (lv.code, base)
        for r in lv.rooms:
            data = r.rle()
            total += len(data)
            out.append('room_%d:    ; %s' % (r.index, r.name))
            out.append('        db %s' % ','.join('%d' % e for e in r.exits))
            out.append('        db %d,%d' % (TL.WORLDS.index(r.world), r.gem_base))
            out.append('        dw room_%d_obj' % r.index)
            out.append(db_lines(data))
            out.append('room_%d_obj:' % r.index)
            for rec in r.recs:
                out.append('        db %s' % ','.join('%d' % v for v in rec))
            out.append('        db 255')
            total += 5 * len(r.recs) + 9
    out.append('LEVELTAB:')
    for i, lv in enumerate(LV.LEVELS):
        sx, sy = lv.first.start
        out.append('        db %d,%d,%d,%d,%d,%d' % (lv.first.index, sx, sy, TL.WORLDS.index(lv.world),
                                                    lv.ngems, 1 if lv.boss else 0))
        out.append('        dw %s,lvname_%d,lvhint_%d' % (lv.song, i, i))
    out.append('LT_SIZE equ 12')
    for i, lv in enumerate(LV.LEVELS):
        out.append('lvname_%d: db "%s",0' % (i, lv.name))
        out.append('lvcode_%d: db "%s",0' % (i, lv.code))
        out.append('lvhint_%d: db "%s",0' % (i, lv.hint))
    out.append('LVCODES: dw ' + ','.join('lvcode_%d' % i for i in range(len(LV.LEVELS))))
    return '\n'.join(out) + '\n', total, rooms


def preview_rooms(rooms):
    from PIL import Image
    import celart as ca
    d = os.path.join(BUILD, 'rooms')
    os.makedirs(d, exist_ok=True)
    kiko = SP.FRAMES['K_STAND'][0]
    for r in rooms:
        im = Image.new('RGB', (320, 23 * 8))
        pic = [[(TL.TILES[t].glyph, TL.CL[TL.TILES[t].fg], TL.CL[TL.TILES[t].bg]) for t in row] for row in r.T]
        ca.draw(im, pic, 0, 0)
        if r.start:
            ca.draw(im, kiko, r.start[0] - 1, r.start[1] - 2)
        for (t, x, y, p1, p2) in r.recs:
            ca.draw(im, [[(0x1B3, 3, ca.TR)]], x, y)
        r.image = im
        im.resize((640, 23 * 16), Image.NEAREST).save(os.path.join(d, ident(r.name) + '.png'))
    # whole levels, rooms in their grid
    for lv in LV.LEVELS:
        gw = max(x for x, y in lv.pos.values()) + 1
        gh = max(y for x, y in lv.pos.values()) + 1
        big = Image.new('RGB', (gw * 324, gh * 188), (40, 40, 40))
        for k, (x, y) in lv.pos.items():
            big.paste(lv.byname[k].image, (x * 324, y * 188))
        big.save(os.path.join(d, 'level_' + ident(lv.code) + '.png'))


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    write('gen_tiles.inc', gen_tiles())
    write('gen_remap.inc', gen_remap())
    spr, spr_total = gen_sprites()
    write('gen_sprites.inc', spr)
    rms, rle_total, rooms = gen_rooms()
    write('gen_rooms.inc', rms)
    write('gen_music.inc', music.gen_asm())
    write('gen_screens.inc', screens.gen_asm())
    write('gen_tables.inc', gen_tables())
    if 'preview' in sys.argv:
        preview_rooms(rooms)
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/kiko.sym',
                        '--lst=../build/kiko.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'kiko.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: %d tiles, %d rooms (%d bytes), sprites %d bytes, binary %d bytes (%04X-%04X)' % (
        NAME, len(TL.TILES), len(rooms), rle_total, spr_total, len(data), LOAD, LOAD + len(data) - 1))


# ---------------------------------------------------------------- misc tables
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c
    return t


def gen_tables():
    out = ['; generated by build.py', '        align 256', 'ATOD:', db_lines(atod()),
           '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    # row tables: ROWOV[r] = OVC + r*40, ROWT[r] = ROOMT + r*40
    out.append('ROWOV: dw ' + ','.join('0%04Xh' % (0xC050 + r * 40) for r in range(23)))
    out.append('ROWT:  dw ' + ','.join('0%04Xh' % (0xB050 + r * 40) for r in range(23)))
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    main()
