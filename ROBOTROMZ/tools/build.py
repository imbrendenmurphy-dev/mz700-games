"""build.py - builds ROBOGEDDON 2085 for the Sharp MZ-700.

    py tools/build.py

Generates build/gen_logo.inc, assembles src/robogeddon.asm with sjasmplus and
wraps the binary as build/ROBOGEDN.MZT (UniCMT, MZ700WIN) plus an identical
.MZF, and copies both to release/.
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
REL = os.path.join(ROOT, 'release')
LOAD = 0x1200
NAME = 'ROBOGEDDON'          # name in the tape header
FILE = 'ROBOGEDN'

# Bold 6x7 letters for the title logo, drawn with the ROM's 2x2 dot blocks
# (display codes F0h + 1 TL + 2 TR + 4 BL + 8 BR).
FONT = {
    'R': ['111110', '110011', '110011', '111110', '110110', '110011', '110011'],
    'O': ['011110', '110011', '110011', '110011', '110011', '110011', '011110'],
    'B': ['111110', '110011', '110011', '111110', '110011', '110011', '111110'],
    'G': ['011111', '110000', '110000', '110111', '110011', '110011', '011111'],
    'E': ['111111', '110000', '110000', '111110', '110000', '110000', '111111'],
    'D': ['111110', '110011', '110011', '110011', '110011', '110011', '111110'],
    'N': ['110011', '111011', '111111', '110111', '110011', '110011', '110011'],
}


def logo(text='ROBOGEDDON'):
    w = len(text) * 7 - 1
    pix = [[0] * (w + 1) for _ in range(8)]
    for i, ch in enumerate(text):
        for y, row in enumerate(FONT[ch]):
            for x, b in enumerate(row):
                if b == '1':
                    pix[y][i * 7 + x] = 1
    cols = (w + 1) // 2
    out = []
    for cy in range(4):
        line = []
        for cx in range(cols):
            tl = pix[cy * 2][cx * 2]
            tr = pix[cy * 2][cx * 2 + 1]
            bl = pix[cy * 2 + 1][cx * 2]
            br = pix[cy * 2 + 1][cx * 2 + 1]
            line.append(0xF0 + tl + 2 * tr + 4 * bl + 8 * br)
        out.append(line)
    return out


def gen_logo():
    rows = logo()
    assert all(len(r) == 35 for r in rows), [len(r) for r in rows]
    lines = ['; generated by tools/build.py - title logo, 4 rows x 35', 'logo:']
    for r in rows:
        lines.append('        db ' + ','.join('%03Xh' % v for v in r))
    with open(os.path.join(BUILD, 'gen_logo.inc'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


def mzf(data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01                               # machine code
    fn = NAME.encode('ascii') + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = LOAD.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)
    gen_logo()
    asm = os.path.join(HERE, 'sjasmplus', 'sjasmplus.exe')
    if not os.path.exists(asm):
        asm = shutil.which('sjasmplus') or sys.exit(
            'needs sjasmplus: put sjasmplus.exe in tools/sjasmplus/ or on the PATH')
    r = subprocess.run([asm, '--nologo', '--sym=../build/robogedn.sym',
                        '--lst=../build/robogedn.lst', 'robogeddon.asm'],
                       cwd=SRC, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    if out:
        print(out)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'robogedn.bin'), 'rb').read()
    image = mzf(data, LOAD)
    for ext in ('MZT', 'MZF'):
        p = os.path.join(BUILD, FILE + '.' + ext)
        with open(p, 'wb') as f:
            f.write(image)
        shutil.copy(p, os.path.join(REL, FILE + '.' + ext))
    print('%s: %d bytes, %04Xh-%04Xh, runs from %04Xh' %
          (FILE, len(data), LOAD, LOAD + len(data) - 1, LOAD))


if __name__ == '__main__':
    main()
