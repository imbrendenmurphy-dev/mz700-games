"""gfx.py - fighter graphics for the assembler.

For each fighter:
  dict  - the distinct (char, attr) cells its frames use (index 1..N, 0 = gap)
  frames - per frame: db height, mincol, maxcol, then rows top to bottom, each a
           list of runs (db col, count, idx...) ended by 80h.  Columns are
           relative to the anchor column (the cell right of the anchor line);
           mirrored, column c is drawn at -1-c.
  boxes  - per frame: hurt box and hit box (cells, relative, y up from ground)

attr bit 3 = transparent background (take the paper underneath).
"""
import os
import sys
import math

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np  # noqa
import figure as FG  # noqa
import fighters as FT  # noqa
import cells  # noqa

HI_LIMIT = 0x2FF0 - 0x100     # high RAM D000-FFEF, less room for other data
HIT_JOINT = {'punch': 'ha_f', 'cpunch': 'ha_f', 'kick': 'toe_f', 'sweep': 'toe_f', 'jkick': 'toe_f',
             'spec_b': 'ha_f', 'throw': 'ha_f', 'spec_a': 'ha_f'}


def frame_cells(img):
    """cells keyed (col, row) with col relative to the anchor cell and row 0 =
    the ground row (y up)."""
    h, w = img.shape
    assert FG.AX % 8 == 0
    out = {}
    for r in range(FG.AY // 8):
        y0 = FG.AY - (r + 1) * 8
        for cc in range(w // 8):
            blk = img[y0:y0 + 8, cc * 8:cc * 8 + 8]
            cell = cells.sprite_cell(blk)
            if cell:
                out[(cc - FG.AX // 8, r)] = cell
    return out


def cell_bytes(cell):
    g, fg, bg, tr = cell
    a = ((g >> 8) << 7) | (fg << 4) | (bg if not tr else 0) | (8 if tr else 0)
    return (g & 255, a)


def toe(J, pose, b):
    an = J['an_f']
    kn = J['kn_f']
    v = (an[0] - kn[0], an[1] - kn[1])
    ln = math.hypot(*v) or 1
    return (an[0] + v[0] / ln * b.foot * 0.6, an[1] + v[1] / ln * b.foot * 0.6)


def boxes(ftr, name, J, cl):
    """hurt box (x0, x1, y0, y1) and hit box (or None), in cells, x relative to
    the anchor, y rows up from the ground (inclusive)."""
    xs = [J['hip'][0], J['neck'][0], J['head'][0]]
    ys = [p[1] for p in J.values()] + [J['head'][1] + ftr.build.head]
    x0 = math.floor((min(xs) - 9) / 8)
    x1 = math.floor((max(xs) + 9) / 8)
    y0 = max(0, math.floor(min(ys) / 8))
    y1 = math.floor(max(ys) / 8)
    if name == 'down':
        hurt = None
    else:
        hurt = (x0, x1, y0, y1)
    hit = None
    jn = HIT_JOINT.get(name)
    if jn:
        p = toe(J, None, ftr.build) if jn == 'toe_f' else J[jn]
        hx = math.floor(p[0] / 8)
        hy = math.floor(p[1] / 8)
        hit = (hx - 1, hx, hy - 1, hy + 1)
    return hurt, hit


def build_fighter(key):
    ftr = FT.FIGHTERS[key]
    dict_ = {}
    order = []
    frames = []
    meta = []
    for fn in FT.FRAMES:
        img, J = FG.draw_figure(ftr.build, ftr.costume, FT.pose(ftr, fn))
        cl = frame_cells(img)
        rows = {}
        for (c, r), cell in cl.items():
            cb = cell_bytes(cell)
            if cb not in dict_:
                order.append(cb)
                dict_[cb] = len(order)
            rows.setdefault(r, {})[c] = dict_[cb]
        top = max(rows) if rows else 0
        cols = [c for (c, r) in cl]
        data = [top + 1, min(cols) & 255, max(cols) & 255]
        for r in range(top, -1, -1):
            row = rows.get(r, {})
            cs = sorted(row)
            i = 0
            while i < len(cs):
                j = i
                run = [row[cs[i]]]
                # join runs across gaps of one or two cells (0 = gap)
                while j + 1 < len(cs) and cs[j + 1] - cs[j] <= 3:
                    for _ in range(cs[j + 1] - cs[j] - 1):
                        run.append(0)
                    run.append(row[cs[j + 1]])
                    j += 1
                data += [cs[i] & 255, len(run)] + run
                i = j + 1
            data.append(0x80)
        frames.append(data)
        hurt, hit = boxes(ftr, fn, J, cl)
        meta.append((hurt, hit, min(cols), max(cols), top + 1))
    assert len(order) <= 255, (key, len(order))
    return ftr, order, frames, meta


def mirror_tables():
    m0 = list(range(256))
    m1 = list(range(256))
    for g in cells.SPRITE_GLYPHS:
        mg = cells.mirror_glyph(g)
        assert (g >> 8) == (mg >> 8), 'mirror crosses banks: %x %x' % (g, mg)
        (m1 if g >= 256 else m0)[g & 255] = mg & 255
    return m0, m1


def s8(v):
    return v & 255


def generate(keys):
    """returns (low lines, high lines): fighter frames go to high RAM, the
    rest (dicts, frame tables, boxes) to the program."""
    lo = ['; generated by tools/gfx.py']
    hi = ['; generated by tools/gfx.py (high RAM)']
    pairs = sorted({(g, cells.mirror_glyph(g)) for g in cells.SPRITE_GLYPHS if cells.mirror_glyph(g) != g})
    for g, m in pairs:
        assert (g >> 8) == (m >> 8)
    lo.append('mir_pairs:              ; glyph (bit 8 = bank) -> mirror, words; FFFFh ends')
    lo.append('        dw ' + ','.join('%d,%d' % (g, m & 255) for g, m in pairs) + ',0FFFFh')
    lo.append('NFRAMES equ %d' % len(FT.FRAMES))
    for i, fn in enumerate(FT.FRAMES):
        lo.append('FR_%s equ %d' % (fn.upper(), i))
    lo.append('FI_NAME equ 7')
    lo.append('FI_ALT equ 9')
    lo.append('FI_LAND equ 17')
    lo.append('ftr_tab:')
    lo.append('        dw ' + ','.join('ftr_%s' % k for k in keys))
    total = 0
    hi_used = [0]
    for k in keys:
        ftr, order, frames, meta = build_fighter(k)
        lo.append('ftr_%s:' % k)
        lo.append('        dw fd_%s, ff_%s, fb_%s, fi_%s' % (k, k, k, k))
        spec = {'fire': 'M_FIRE', 'flurry': 'M_FLURRY', 'rush': 'M_RUSH', 'upper': 'M_UPPER', 'spin': 'M_SPIN',
                'dive': 'M_DIVE'}
        alt = [ftr.alt.get(c, c) for c in range(8)]
        lo.append('fi_%s:   db %s,%s,%d,%d,%d' % (k, spec[ftr.spa], spec[ftr.spb], 1 if ftr.spb == 'upper' else 0,
                                                 ftr.speed, ftr.power))
        lo.append('        dw pa_%s, fn_%s' % (ftr.proj, k))
        lo.append('        db ' + ','.join(str(v) for v in alt))
        lo.append('        dw fl_%s' % k)
        lo.append('fn_%s:   db "%s",0' % (k, ftr.name))
        lo.append('fl_%s:   db "%s",0' % (k, ftr.country))
        lo.append('fd_%s:   db %d' % (k, len(order)))
        for i in range(0, len(order), 16):
            lo.append('        db ' + ','.join(str(c) for c, a in order[i:i + 16]))
        for i in range(0, len(order), 16):
            lo.append('        db ' + ','.join(str(a) for c, a in order[i:i + 16]))
        lo.append('ff_%s:' % k)
        lo.append('        dw ' + ','.join('fr_%s_%d' % (k, i) for i in range(len(frames))))
        lo.append('fb_%s:   ; hurt x0,x1,y0,y1  hit x0,x1,y0,y1 (80h = none)  minc,maxc,height' % k)
        for hurt, hit, mn, mx, h in meta:
            a = [s8(v) for v in hurt] if hurt else [0x80, 0x80, 0x80, 0x80]
            b = [s8(v) for v in hit] if hit else [0x80, 0x80, 0x80, 0x80]
            lo.append('        db ' + ','.join(str(v) for v in a + b))
        for i, d in enumerate(frames):
            # frames fill the high RAM first, then spill into the program
            dest = hi if hi_used[0] + len(d) <= HI_LIMIT else lo
            if dest is hi:
                hi_used[0] += len(d)
            dest.append('fr_%s_%d:' % (k, i))
            for j in range(0, len(d), 24):
                dest.append('        db ' + ','.join(str(v) for v in d[j:j + 24]))
            total += len(d)
        total += 1 + 2 * len(order)
        print('fighter %s: %d dict cells, %d frame bytes' % (k, len(order), sum(len(d) for d in frames)))
    return lo, hi, total


if __name__ == '__main__':
    lo, hi, total = generate(list(FT.FIGHTERS))
    print(total)
