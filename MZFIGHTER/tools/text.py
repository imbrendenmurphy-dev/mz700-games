ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54,
         '@': 0x55, '_': 0x3C, '^': 0x50, '|': 0x75}
COL = {'k': 0, 'b': 1, 'r': 2, 'm': 3, 'g': 4, 'c': 5, 'y': 6, 'w': 7}


def atod():
    t = []
    for c in range(0x20, 0x80):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t.append(c - 64)
        elif 'a' <= ch <= 'z':
            t.append(c - 96 + 0x80)
        elif '0' <= ch <= '9':
            t.append(0x20 + c - 48)
        else:
            t.append(ASCII.get(ch, 0))
    return t


def enc(s):
    out = []
    i = 0
    while i < len(s):
        if s[i] == '{' and s[i + 2:i + 3] == '}':
            v = COL[s[i + 1]]
            out.append(v if v else 8)
            i += 3
            continue
        out.append(ord(s[i]))
        i += 1
    return out + [0]


def db(label, vals):
    lines = [label + ':'] if label else []
    for i in range(0, len(vals), 16):
        lines.append('        db ' + ','.join(str(v & 0xFF) for v in vals[i:i + 16]))
    return lines


