def gen_asm():
    out = ['; generated by tools/text.py']
    out += db('atod_src', atod())
    for k, s in STRINGS.items():
        out += db(k, enc(s))
    for i, s in enumerate(ENDINGS):
        out += db('s_end%d' % i, enc(s.replace('|', chr(10))))
    out.append('end_tab: dw ' + ','.join('s_end%d' % i for i in range(len(ENDINGS))))
    return '\n'.join(out) + '\n'
