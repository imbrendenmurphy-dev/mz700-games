def bitmap(s, gap=1):
    """-> list of 5 strings (half-cell columns)"""
    rows = [''] * 5
    for i, ch in enumerate(s):
        g = F[ch]
        for r in range(5):
            rows[r] += g[r] + ('.' * gap if i < len(s) - 1 else '')
    if len(rows[0]) % 2:
        rows = [r + '.' for r in rows]
    return rows
