"""stage.py - stage backgrounds (screen rows 3-24 = 40 x 22 cells).

Each stage is drawn as a 320 x 176 colour-index picture (draw(phase)) and
matched cell by cell to ROM glyphs (two colours per cell).  Animated layers
render the picture at each phase and keep only the cells of the layer's
region that change.
"""
import os
import sys
import math
import random
import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cells  # noqa
import crunch  # noqa
import mzfont as F  # noqa
from figure import BLACK, BLUE, RED, MAGENTA, GREEN, CYAN, YELLOW, WHITE  # noqa

W, H = 320, 176
COLS, ROWS = 40, 22
ROW0 = 3


def _bg_glyphs():
    bad = set(range(0x01, 0x1B)) | set(range(0x20, 0x2A)) | set(range(0x81, 0x9B)) | \
        set(range(0x101, 0x11B)) | set(range(0x120, 0x12A)) | {0x49, 0x4F, 0x2C, 0x2F, 0x61, 0x62, 0x63, 0x64,
                                                               0x65, 0x66, 0x67}
    # pictures that pop up in textures (invaders, people, cars...)
    bad |= set(range(0x125, 0x15C)) | set(range(0x1E0, 0x200)) | set(range(0xC0, 0xCC)) | set(range(0x1A6, 0x1B6))
    return [g for g in cells.ALL_GLYPHS if g not in bad]


BG_GLYPHS_ALL = _bg_glyphs()
# clean shapes only: the sprite set plus checkers and dot textures
BG_GLYPHS = sorted(set(cells.SPRITE_GLYPHS) | {0xD0, 0xEF, 0x5B, 0x6C, 0x1A2, 0x1A3, 0x1A4, 0x186, 0x185}
                   | set(range(0xF0, 0x100)))


class Pic:
    """a drawing surface of colour indices with dithered fills"""
    def __init__(self, fill=BLACK):
        self.a = np.full((H, W), fill, np.uint8)
        self.im = None

    def img(self):
        im = Image.fromarray(self.a, 'P')
        return im, ImageDraw.Draw(im)

    def put(self, im):
        self.a = np.array(im, dtype=np.uint8)

    def band(self, y0, y1, c):
        self.a[y0:y1, :] = c

    def dither(self, mask, c1, c2, level):
        """level 0..4 of c2 over c1 in an ordered 2x2 pattern, on mask"""
        yy, xx = np.mgrid[0:H, 0:W]
        bayer = np.array([[0, 2], [3, 1]])
        t = bayer[yy % 2, xx % 2]
        sel = t < level
        self.a[mask & ~sel] = c1
        self.a[mask & sel] = c2

    def rect(self, x0, y0, x1, y1, c):
        self.a[max(0, y0):max(0, y1), max(0, x0):max(0, x1)] = c

    def poly(self, pts, c):
        im, d = self.img()
        d.polygon(pts, fill=c)
        self.put(im)

    def ellipse(self, box, c):
        im, d = self.img()
        d.ellipse(box, fill=c)
        self.put(im)

    def line(self, pts, c, w=1):
        im, d = self.img()
        d.line(pts, fill=c, width=w)
        self.put(im)


def ymask(y0, y1):
    m = np.zeros((H, W), bool)
    m[y0:y1, :] = True
    return m


def to_cells(a):
    out = []
    for r in range(ROWS):
        for c in range(COLS):
            out.append(cells.bg_cell(a[r * 8:r * 8 + 8, c * 8:c * 8 + 8], BG_GLYPHS, 6.0))
    return out


def cell_bytes(cell):
    g, fg, bg = cell
    if fg == bg:
        return (0, bg)
    return (g & 255, ((g >> 8) << 7) | (fg << 4) | bg)


# ---------------------------------------------------------------- stages
def sky_gradient(p, bands):
    """bands: list of (y, colour, colour2, level) from the top"""
    for i, (y0, c1, c2, lv) in enumerate(bands):
        y1 = bands[i + 1][0] if i + 1 < len(bands) else H
        p.dither(ymask(y0, y1), c1, c2, lv)


def _stages():
    import stages_art
    return stages_art.STAGE_LIST


def build(stage):
    name, fn, layers = stage
    base = fn(0)
    basec = [cell_bytes(c) for c in to_cells(base)]
    lay = []
    for (c0, r0, c1, r1), nph, period in layers:
        grids = [basec] + [[cell_bytes(c) for c in to_cells(fn(p))] for p in range(1, nph)]
        S = [r * COLS + c for r in range(r0, r1) for c in range(c0, c1)
             if any(g[r * COLS + c] != basec[r * COLS + c] for g in grids)]
        phases = []
        for k, g in enumerate(grids):
            prev = grids[k - 1]          # phases are deltas, applied in a cycle
            D = [i for i in S if g[i] != prev[i]]
            runs = []
            i = 0
            while i < len(D):
                j = i
                while j + 1 < len(D) and D[j + 1] == D[j] + 1:
                    j += 1
                runs.append((D[i] + ROW0 * COLS, [g[k2] for k2 in D[i:j + 1]]))
                i = j + 1
            phases.append(runs)
        lay.append((period, phases))
    return basec, lay


ANIM_BUF = 0xBBE8          # spare BG bytes behind the attribute plane
ANIM_MAX = 0xC000 - ANIM_BUF


def gen_asm():
    out = ['; generated by tools/stage.py', 'ANIM_BUF equ 0%04Xh' % ANIM_BUF]
    STAGES = _stages()
    out.append('stage_tab:')
    for s in STAGES:
        out.append('        dw stg_%s, sta_%s, %d' % (s[0], s[0], 0))
    total = 0
    for s in STAGES:
        name = s[0]
        basec, lay = build(s)
        raw = bytes([c for c, a in basec] + [a for c, a in basec])
        blob = bytearray()
        script = ['sta_%s: db %d' % (name, len(lay))]
        lay_lines = []
        for li, (period, phases) in enumerate(lay):
            ptrs = []
            for runs in phases:
                ptrs.append(ANIM_BUF + len(blob))
                for off, cl in runs:
                    blob += bytes([off & 255, off >> 8, len(cl)]) + bytes(sum(([c, a] for c, a in cl), []))
                blob += bytes([255, 255])
            lay_lines.append('stl_%s_%d: db %d,%d' % (name, li, period, len(phases)))
            lay_lines.append('        dw ' + ','.join('0%04Xh' % p for p in ptrs))
        assert len(blob) <= ANIM_MAX, (name, len(blob))
        script.append('        dw ' + ','.join('stl_%s_%d' % (name, i) for i in range(len(lay))) if lay else '')
        pk = crunch.pack(raw + bytes(blob))
        assert crunch.unpack(pk) == raw + bytes(blob)
        out.append('stg_%s:   ; %d bytes unpacked (picture 1760 + animation %d)' % (name, len(raw) + len(blob), len(blob)))
        for i in range(0, len(pk), 32):
            out.append('        db ' + ','.join(str(v) for v in pk[i:i + 32]))
        out += script + lay_lines
        out.append('stb_%s equ %d' % (name, len(blob)))
        size = len(pk) + 1 + 2 * len(lay) + sum(2 + 2 * len(ph) for _, ph in lay)
        print('stage %s: %d bytes' % (name, size))
        total += size
    # fill the blob lengths in the table
    tab = out.index('stage_tab:')
    for k, s in enumerate(STAGES):
        out[tab + 1 + k] = '        dw stg_%s, sta_%s, stb_%s' % (s[0], s[0], s[0])
    return '\n'.join(out) + '\n', total


def preview(name, out, phase=0):
    s = [x for x in _stages() if x[0] == name][0]
    a = s[1](phase)
    cl = [cell_bytes(c) for c in to_cells(a)]
    chars = [0] * 120 + [c for c, at in cl]
    attrs = [0x11] * 120 + [at for c, at in cl]
    im = F.render_cells(chars, attrs, scale=2)
    pix = Image.fromarray(a, 'P')
    pix.putpalette(sum((list(c) for c in F.PAL), []) + [0] * (256 * 3 - 24))
    big = Image.new('RGB', (640, 400 + 352 + 8))
    big.paste(im, (0, 0))
    big.paste(pix.convert('RGB').resize((640, 352), Image.NEAREST), (0, 408))
    big.save(out)


if __name__ == '__main__':
    preview(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else '../build/stage.png')
