"""build.py - builds GHOST HUNTER 2 for the Sharp MZ-700.

    py build.py

Generates the data tables (build/gen_*.inc), assembles src/main.asm with
sjasmplus and writes build/GHOST2.MZT (emulators) plus an identical
GHOST2.MZF (UniCMT / real hardware); both are copied to release/.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(ROOT, 'tools')
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
REL = os.path.join(ROOT, 'release')
sys.path.insert(0, TOOLS)

import mazes  # noqa: E402
import looks  # noqa: E402
import music  # noqa: E402
import art  # noqa: E402

NAME = 'GHOST2'
TAPENAME = 'GHOST HUNTER 2'
LOAD = 0x1200


def db_lines(vals, per=16):
    return '\n'.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


# ---------------------------------------------------------------- tables
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c
    return t


def gen_tables():
    out = ['; generated by build.py', '        align 256', 'ATOD:', db_lines(atod()),
           '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    # screen address of grid (0, y): row y + 1, column -1
    out.append('SROW:   dw ' + ','.join('0%04Xh' % (0xD000 + (y + 1) * 40 - 1) for y in range(21)))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- mazes
def attr(gl, fg, bg):
    return ((gl >> 8) << 7) | (fg << 4) | bg


def palette(style, power):
    """attr per class 0..8 (bank bit from the class's glyph)"""
    glyph_bank = {1: 0x185, 2: 0x186, 6: 0x184}
    out = []
    for cls in range(9):
        code = 3 if cls == 8 else cls
        look = -1 if cls == 8 else 0x078
        if cls in (4,):
            look = looks.DOOR_G
        g, f, b = looks.cell_look(code, look, style, power)
        if cls in glyph_bank:
            g = glyph_bank[cls]
        if cls in (0, 5, 7):
            f = b
        out.append(attr(g, f, b))
    return out


def gen_mazes():
    out = ['; generated by build.py - the mazes',
           'MAZETAB: dw ' + ','.join('maze_%d' % i for i in range(len(mazes.MAZES)))]
    total = 0
    for i, (name, title, g, style) in enumerate(mazes.all_grids()):
        lk = looks.wall_looks(g)
        lc, ig, ic = looks.STYLES[style]
        cls = []
        glyph = []
        for y in range(mazes.GH):
            for x in range(mazes.GW):
                v = g[y][x]
                if v == mazes.WALL and lk[y][x] == -1:
                    cls.append(8)
                    glyph.append(ig & 0xFF)
                else:
                    cls.append(v)
                    glyph.append(lk[y][x] & 0xFF if v in (mazes.WALL, mazes.DOOR) else 0)
        # wall interiors in the second character set need the bank bit in the palette
        out.append('maze_%d:' % i)
        out.append('        db %d' % style)
        out.append('        dw mname_%d, mpal_%d_0, mpal_%d_1' % (i, i, i))
        out.append(db_lines(cls, 41))
        out.append(db_lines(glyph, 41))
        for p in (0, 1):
            pal = palette(style, p)
            if ig >= 0x100:
                pal[8] |= 0x80
            out.append('mpal_%d_%d: db %s' % (i, p, ','.join('%d' % v for v in pal)))
        out.append('mname_%d: db "MAZE %s  %s",0' % (i, name, title))
        total += len(cls) * 2
    return '\n'.join(out) + '\n', total


# ---------------------------------------------------------------- art
def cell_bytes(c):
    if c is None:
        return 0, 0
    g, f, b = c[0], c[1], (c[2] if len(c) > 2 else -1)
    at = ((g >> 8) << 7) | (f << 4)
    if b != -1:
        at |= 8 | b
    return g & 0xFF, at


def gen_art():
    out = ['; generated by build.py - title picture and big sprites']
    pic, stars = art.title_picture()
    ch, at = [], []
    for row in pic:
        for g, f, b in row:
            ch.append(g & 0xFF)
            at.append(attr(g, f, b))
    out += ['TITLE_CH:', db_lines(ch, 40), 'TITLE_AT:', db_lines(at, 40)]
    out.append('NSTARS equ %d' % len(stars))
    out.append('STARS:  dw ' + ','.join('0%04Xh' % (0xD000 + y * 40 + x) for x, y in stars))
    sp = art.big_sprites()
    names = list(sp.keys())
    for i, n in enumerate(names):
        out.append('%s equ %d' % (n, i))
    out.append('BIGTAB: dw ' + ','.join('big_%s' % n for n in names))
    for n in names:
        cl = sp[n]
        assert len(cl) == 3 and all(len(r) == 3 for r in cl), n
        b = []
        for row in cl:
            for c in row:
                b += cell_bytes(c)
        out.append('big_%s: db %s' % (n, ','.join('%d' % v for v in b)))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    write('gen_tables.inc', gen_tables())
    mz, msize = gen_mazes()
    write('gen_mazes.inc', mz)
    write('gen_music.inc', music.gen_asm())
    write('gen_art.inc', gen_art())
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/ghost2.sym',
                        '--lst=../build/ghost2.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'ghost2.bin'), 'rb').read()
    out = mzf(TAPENAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: %d mazes (%d bytes), binary %d bytes (%04X-%04X)' % (
        NAME, len(mazes.MAZES), msize, len(data), LOAD, LOAD + len(data) - 1))


if __name__ == '__main__':
    main()
