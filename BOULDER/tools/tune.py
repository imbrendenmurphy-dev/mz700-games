"""tune.py - solve every cave with the bot, set its clock, save the solutions.

    py tools/tune.py [letters]

Writes tools/solutions.py: for each cave the clock (twice the bot's time
plus 40 s, rounded up to 10, 60-250 s) and the winning keys, run-length
coded.  build.py replays every solution on the Python model and refuses to
build if one no longer wins; tools/verify.py replays them on the Z80 build.
"""
import math
import os
import pprint
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bot  # noqa: E402
import caves as C  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'solutions.py')


def rle(keys):
    out = []
    for k in keys:
        if out and out[-1][0] == k and out[-1][1] < 255:
            out[-1][1] += 1
        else:
            out.append([k, 1])
    return [tuple(p) for p in out]


def unrle(pairs):
    keys = []
    for k, n in pairs:
        keys += [k] * n
    return keys


def load():
    try:
        sys.path.insert(0, HERE)
        import solutions
        return dict(solutions.SOLUTIONS)
    except ImportError:
        return {}


def clock_for(ticks, tps):
    secs = ticks / tps
    return max(60, min(250, int(math.ceil((secs * 2 + 40) / 10.0)) * 10))


def main():
    want = sys.argv[1] if len(sys.argv) > 1 else None
    sols = load()
    cs = C.caves()
    for i, c in enumerate(cs):
        if want and c.letter not in want:
            continue
        ok, res, g = bot.solve(c, i)
        if not ok:
            print('%s %-18s FAILED: %s (%d/%d gems)' % (c.letter, c.name, res, g.got, c.need))
            sols.pop(c.letter, None)
            continue
        t = clock_for(len(res), g.tps)
        sols[c.letter] = dict(time=t, ticks=len(res), keys=rle(res))
        print('%s %-18s %4d ticks -> clock %3d s, %d runs' % (c.letter, c.name, len(res), t, len(sols[c.letter]['keys'])))
    with open(OUT, 'w') as f:
        f.write('"""solutions.py - generated by tools/tune.py: clock and winning keys per cave."""\n')
        f.write('SOLUTIONS = ')
        f.write(pprint.pformat(sols, width=110, compact=True))
        f.write('\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
