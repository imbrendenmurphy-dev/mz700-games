"""tune.py - solve every cave with the bot, set its clock, save the solutions.

    py tools/tune.py [letters]

Writes tools/solutions.py: for each cave the clock (twice the bot's time
plus 40 s, rounded up to 10, 60-250 s) and the winning keys, run-length
coded.  build.py replays every solution on the Python model and refuses to
build if one no longer wins; tools/verify.py replays them on the Z80 build.
"""
import math
import os
import pprint
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bot  # noqa: E402
import caves as C  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'solutions.py')


def rle(keys):
    out = []
    for k in keys:
        if out and out[-1][0] == k and out[-1][1] < 255:
            out[-1][1] += 1
        else:
            out.append([k, 1])
    return [tuple(p) for p in out]


def unrle(pairs):
    keys = []
    for k, n in pairs:
        keys += [k] * n
    return keys


def load():
    try:
        sys.path.insert(0, HERE)
        import solutions
        return dict(solutions.SOLUTIONS)
    except ImportError:
        return {}


def clock_for(ticks, tps, bonus=False):
    secs = ticks / tps
    if bonus:                            # a bonus cave is a dash: a third over the bot's time
        return max(30, min(120, int(math.ceil((secs * 1.35 + 10) / 5.0)) * 5))
    return max(60, min(250, int(math.ceil((secs * 2 + 40) / 10.0)) * 10))


def merge():
    """fold the part files of parallel runs (tune.py LETTERS --part) into solutions.py"""
    sols = load()
    for fn in sorted(os.listdir(HERE)):
        if fn.startswith('solpart_') and fn.endswith('.txt'):
            part = eval(open(os.path.join(HERE, fn)).read())
            sols.update(part['ok'])
            for k in part['failed']:
                sols.pop(k, None)
            os.remove(os.path.join(HERE, fn))
    write(sols)


def write(sols):
    with open(OUT, 'w') as f:
        f.write('"""solutions.py - generated by tools/tune.py: clock and winning keys per cave."""\n')
        f.write('SOLUTIONS = ')
        f.write(pprint.pformat(sols, width=110, compact=True))
        f.write('\n')
    print('wrote', OUT)


def main():
    if sys.argv[1:2] == ['merge']:
        return merge()
    want = sys.argv[1] if len(sys.argv) > 1 else None
    part = '--part' in sys.argv
    sols = {} if part else load()
    failed = []
    cs = C.caves()
    for i, c in enumerate(cs):
        if want and c.letter not in want:
            continue
        c.time = 250                     # solve against the longest clock, then set it
        ok, res, g = bot.solve(c, i)
        if not ok:
            print('%s %-18s FAILED: %s (%d/%d gems)' % (c.letter, c.name, res, g.got, c.need))
            sols.pop(c.letter, None)
            failed.append(c.letter)
            continue
        t = clock_for(len(res), g.tps, c.flags & 1)
        sols[c.letter] = dict(time=t, ticks=len(res), keys=rle(res))
        print('%s %-18s %4d ticks -> clock %3d s, %d runs, %d/%d gems' % (
            c.letter, c.name, len(res), t, len(sols[c.letter]['keys']), g.got, c.need), flush=True)
    if part:
        with open(os.path.join(HERE, 'solpart_%s.txt' % want), 'w') as f:
            f.write(repr(dict(ok=sols, failed=failed)))
        print('part done', want)
    else:
        write(sols)


if __name__ == '__main__':
    main()
