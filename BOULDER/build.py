"""build.py - builds ROCKFALL for the Sharp MZ-700.

    py build.py

Generates the data tables (build/gen_*.inc), assembles src/main.asm with
sjasmplus and writes build/ROCKFALL.MZT (emulators) plus an identical
ROCKFALL.MZF (UniCMT / real hardware); both are copied to release/.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(ROOT, 'tools')
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
REL = os.path.join(ROOT, 'release')
sys.path.insert(0, TOOLS)

import caves  # noqa: E402
import engine  # noqa: E402
import music  # noqa: E402
import solutions  # noqa: E402
import tune  # noqa: E402

NAME = 'ROCKFALL'
LOAD = 0x1200


def db_lines(vals, per=16):
    return '\n'.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


def asm_str(s):
    s = s.replace('"', "'")
    return 'db "%s",0' % s


# ---------------------------------------------------------------- tables
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c          # raw display codes pass through
    return t


HANDLER = {'BOULDER': 'h_rest', 'DIAMOND': 'h_rest', 'BOULDERF': 'h_fall', 'DIAMONDF': 'h_fall',
           'AMOEBA': 'h_amoeba', 'PLAYER': 'h_player', 'EXPWALL': 'h_expwall', 'INBOX': 'h_inbox',
           'SHOWER': 'h_shower'}


def handler(name):
    if name in HANDLER:
        return HANDLER[name]
    if name[:4] in ('FIRE', 'BUTT'):
        return 'h_fly'
    if name.startswith('EXP'):
        return 'h_exp'
    if name.startswith('DEX'):
        return 'h_dex'
    return 'h_none'


def gen_tables():
    out = ['; generated by build.py']
    for i, n in enumerate(caves.ELEMS):
        out.append('E_%s equ %d' % (n, i))
    # the scan treats every code below E_BOULDER as inert
    assert all(caves.E[n] < caves.E['BOULDER'] for n in ('DIRT', 'BRICK', 'MAGIC', 'STEEL', 'EXIT', 'EXITO'))
    assert caves.E['BOULDERF'] == caves.E['BOULDER'] + 1 and caves.E['DIAMONDF'] == caves.E['DIAMOND'] + 1
    assert caves.E['DEX4'] == caves.E['DEX1'] + 3 and caves.E['EXP4'] == caves.E['EXP1'] + 3
    for k, v in (('NEED', 0), ('DVAL', 1), ('XVAL', 2), ('TIME', 3), ('MAGIC', 4), ('AMOEBA', 5),
                 ('SPEED', 6), ('LETTER', 7), ('NAME', 8), ('HINT', 10), ('SHRATE', 12), ('SHHAZ', 13),
                 ('SHMAX', 14), ('THEME', 15), ('W', 16), ('H', 17), ('DATA', 18)):
        out.append('CH_%s equ %d' % (k, v))
    out += ['        align 256', 'ATOD:', db_lines(atod()), '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    out += ['        align 256', 'JTAB:']
    out.append('        dw ' + ','.join(handler(n) for n in caves.ELEMS))
    out += ['DIROFF: dw -1,-%d,1,%d' % (caves.MW, caves.MW)]
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- looks
def gen_looks():
    """one display-pair table shared by every theme; per theme an ANIMIDX
    image (256) and a LOOKIDX image, copied into place by set_theme"""
    pairs = {}

    def idx(c):
        if c not in pairs:
            pairs[c] = len(pairs)
        return pairs[c]

    out = ['; generated by build.py - tile looks']
    images = []
    for t in range(len(caves.THEMES)):
        look, extra = caves.theme_looks(t)
        anim = [0] * 256
        for e, name in enumerate(caves.ELEMS):
            assert len(look[name]) == 8, name
            for p in range(8):
                anim[(p << 5) | e] = idx(look[name][p])
        extra = dict(extra)
        extra['LK_SPACE'] = look['SPACE']
        extra['LK_FLASH'] = caves.same(caves.cell(0x00, caves.WHITE, caves.WHITE))
        lkidx = []
        for k, (nm, lk) in enumerate(extra.items()):
            if t == 0:
                out.append('%s equ %d' % (nm, k * 8))
            lkidx += [idx(c) for c in lk]
        images.append((anim, lkidx))
    assert len(pairs) < 255, len(pairs)
    ch = [0] * 256
    at = [0] * 256
    for (c, a), i in pairs.items():
        ch[i], at[i] = c, a
    out += ['NTHEMES equ %d' % len(images), 'LOOKSZ equ %d' % len(images[0][1]),
            '        align 256', 'ANIMIDX:', db_lines(images[0][0]), 'DISP_CH:', db_lines(ch),
            'DISP_AT:', db_lines(at), 'LOOKIDX:', db_lines(images[0][1]),
            'THEMETAB: dw ' + ','.join('theme_%d' % t for t in range(len(images)))]
    for t, (anim, lkidx) in enumerate(images):
        out += ['theme_%d:' % t, db_lines(anim), db_lines(lkidx)]
    return '\n'.join(out) + '\n', len(pairs)


# ---------------------------------------------------------------- caves
def check_solutions(cs):
    """every cave's recorded solution must still win on the Python model"""
    bad = []
    for i, c in enumerate(cs):
        sol = solutions.SOLUTIONS.get(c.letter)
        if not sol:
            bad.append('%s has no solution' % c.letter)
            continue
        c.time = sol['time']
        g = engine.Game(i, c)
        for k in tune.unrle(sol['keys']):
            g.tick(k)
            if g.pl_dead or g.timeout:
                break
        if not g.pl_exit:
            bad.append('%s: the solution no longer wins (got %d/%d, dead %d)' % (c.letter, g.got, c.need, g.pl_dead))
    if bad:
        sys.exit('caves changed - run py tools/tune.py\n  ' + '\n  '.join(bad))


def gen_demo(cs):
    """the solutions as (keys, count) byte pairs, 0-count terminated, for the demo"""
    out = ['; generated by build.py - recorded solutions for the attract demo',
           'DEMOTAB: dw ' + ','.join('demo_%d' % i for i in range(len(cs)))]
    total = 0
    for i, c in enumerate(cs):
        sol = solutions.SOLUTIONS.get(c.letter)
        if sol is None and '--draft' in sys.argv:
            sol = {'keys': []}                # draft: a cave not solved yet has no demo
        pairs = sol['keys']
        vals = [v for k, n in pairs for v in (k, n)] + [0, 0]
        total += len(vals)
        out.append('demo_%d:' % i)
        out.append(db_lines(vals))
    return '\n'.join(out) + '\n', total


def gen_caves():
    cs = caves.caves()
    if '--draft' not in sys.argv:            # draft: test builds while caves change
        check_solutions(cs)
    out = ['; generated by build.py - the caves',
           'NCAVES equ %d' % len(cs),
           'CAVETAB: dw ' + ','.join('cave_%d' % i for i in range(len(cs)))]
    packed = 0
    for i, c in enumerate(cs):
        c.check()
        assert len(c.hint) <= 38 and len(c.name) <= 30, (c.letter, 'hint or name too wide for the cave card')
        data = caves.pack(c)
        assert caves.unpack(c, data) == [caves.E[c.g[y][x]] for y in range(1, c.h - 1) for x in range(1, c.w - 1)]
        packed += len(data)
        out.append('cave_%d:' % i)
        out.append('        db %d,%d,%d,%d,%d,%d,%d,"%s"' % (
            c.need, c.dval, c.xval, c.time, c.magic, c.amoeba, c.speed, c.letter))
        out.append('        dw cname_%d, chint_%d' % (i, i))
        assert 0 <= c.theme < len(caves.THEMES), c.letter
        out.append('        db %d,%d,%d,%d,%d,%d' % (c.shrate, c.shhaz, c.shmax, c.theme, c.w, c.h))
        out.append(db_lines(data))
    for i, c in enumerate(cs):
        out.append('cname_%d: %s' % (i, asm_str(c.name)))
        out.append('chint_%d: %s' % (i, asm_str(c.hint)))
    demo, demo_bytes = gen_demo(cs)
    print('caves %d bytes packed, demo solutions %d bytes' % (packed, demo_bytes))
    return '\n'.join(out) + '\n' + demo, len(cs)


# ---------------------------------------------------------------- logo
LOGO_TXT = {
    'R': ['###\\', '#..#', '#..#', '###J', '#.\\.', '#.L\\', '#..#'],
    'O': ['/##\\', '#..#', '#..#', '#..#', '#..#', '#..#', 'L##J'],
    'C': ['/###', '#...', '#...', '#...', '#...', '#...', 'L###'],
    'K': ['#../', '#./J', '#/J.', '##..', '#L\\.', '#.L\\', '#..#'],
    'F': ['####', '#...', '#...', '###.', '#...', '#...', '#...'],
    'A': ['/##\\', '#..#', '#..#', '####', '#..#', '#..#', '#..#'],
    'L': ['#...', '#...', '#...', '#...', '#...', '#...', '####'],
}
LOGO_CH = {'#': 0x43, '.': 0x00, '/': 0x4E, '\\': 0x4D, 'L': 0x42, 'J': 0x56}


def gen_logo():
    word = NAME
    rows = []
    for y in range(7):
        row = []
        for ch in word:
            row += [LOGO_CH[c] for c in LOGO_TXT[ch][y]] + [0]
        rows.append((row + [0] * 40)[:40])
    out = ['; generated by build.py - title logo', 'LOGO_H equ 7', 'LOGO:']
    for r in rows:
        out.append(db_lines(r, 20))
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    write('gen_tables.inc', gen_tables())
    looks, npairs = gen_looks()
    write('gen_looks.inc', looks)
    cave_text, ncaves = gen_caves()
    write('gen_caves.inc', cave_text)
    write('gen_music.inc', music.gen_asm())
    write('gen_logo.inc', gen_logo())
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/rockfall.sym',
                        '--lst=../build/rockfall.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'rockfall.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: %d caves, %d tile looks, binary %d bytes (%04X-%04X)' % (
        NAME, ncaves, npairs, len(data), LOAD, LOAD + len(data) - 1))


if __name__ == '__main__':
    main()
