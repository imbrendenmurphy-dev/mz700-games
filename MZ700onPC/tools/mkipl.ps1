# Rebuilds src\FdIpl.cs from tools\fdipl.asm (the built-in floppy IPL ROM).
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$sj = Join-Path $here "..\..\ROBOTROMZ\tools\sjasmplus\sjasmplus.exe"
Push-Location $here
& $sj --raw=fdipl.bin fdipl.asm
Pop-Location
$b = [IO.File]::ReadAllBytes((Join-Path $here "fdipl.bin"))
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// Generated by tools\mkipl.ps1 from tools\fdipl.asm - the built-in MZ-1E05 stand-in IPL (F000h). Do not edit.")
[void]$sb.AppendLine("public static class FdIpl")
[void]$sb.AppendLine("{")
[void]$sb.Append("    public static readonly byte[] Code = {")
for ($i = 0; $i -lt $b.Length; $i++) {
    if ($i % 24 -eq 0) { [void]$sb.Append("`r`n        ") }
    [void]$sb.Append(("0x{0:X2}," -f $b[$i]))
}
[void]$sb.AppendLine("`r`n    };")
[void]$sb.AppendLine("}")
[IO.File]::WriteAllText((Join-Path $here "..\src\FdIpl.cs"), $sb.ToString())
Write-Host ("FdIpl.cs: " + $b.Length + " bytes")
