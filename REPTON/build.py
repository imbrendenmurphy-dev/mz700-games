"""build.py - builds SKINK for the Sharp MZ-700.

    py build.py

Generates the data tables (build/gen_*.inc) from the Python definitions in
tools/ (tiles, world, music), assembles src/main.asm with sjasmplus and
writes build/SKINK.MZT (emulators) plus an identical SKINK.MZF (UniCMT /
real hardware); both are copied to release/.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.join(ROOT, 'tools')
BUILD = os.path.join(ROOT, 'build')
SRC = os.path.join(ROOT, 'src')
REL = os.path.join(ROOT, 'release')
sys.path.insert(0, TOOLS)

import tiles  # noqa: E402
import world  # noqa: E402
import music  # noqa: E402
import engine  # noqa: E402
import logo  # noqa: E402

NAME = 'SKINK'
LOAD = 0x1200


def db_lines(vals, per=16):
    return '\n'.join('        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


def dw_lines(vals, per=8):
    return '\n'.join('        dw ' + ','.join('%s' % v for v in vals[i:i + per])
                     for i in range(0, len(vals), per))


# ---------------------------------------------------------------- text
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96 + 0x80      # lower case (bank 1 of the display codes)
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c          # raw display codes pass through
    return t


def asm_str(s):
    s = s.replace('"', "'")
    return ('db "%s",0' % s) if s else 'db 0'


# ---------------------------------------------------------------- tables
HANDLER = {'PLAYER': 'h_player', 'ROCK': 'h_rest', 'EGG': 'h_rest', 'ROCKF': 'h_fall', 'EGGF': 'h_fall',
           'HATCH1': 'h_hatch', 'HATCH2': 'h_hatch', 'HATCH3': 'h_hatch', 'MONSTER': 'h_monster',
           'FUNGUS': 'h_fungus'}
PCLASS = {'SPACE': 1, 'EARTH': 1, 'SECRET': 1, 'GEM': 2, 'PIECE': 3, 'CROWN': 4, 'KEY': 5,
          'ROCK': 6, 'EGG': 6, 'TRANS': 7, 'SWITCH': 8, 'GATE': 9,
          'MONSTER': 10, 'SKULL': 10, 'FUNGUS': 10, 'SPIRIT0': 10, 'SPIRIT1': 10, 'SPIRIT2': 10,
          'SPIRIT3': 10}
CNT = {'GEM': 1, 'CAGE': 1, 'SAFE': 1, 'PIECE': 2, 'CROWN': 3,
       'EGG': 4, 'EGGF': 4, 'HATCH1': 4, 'HATCH2': 4, 'HATCH3': 4, 'MONSTER': 4}


def gen_tables():
    out = ['; generated by build.py']
    for i, n in enumerate(tiles.ELEMS):
        out.append('E_%s equ %d' % (n, i))
    E = tiles.E
    assert E['ROCKF'] == E['ROCK'] + 1 and E['EGGF'] == E['EGG'] + 1
    assert E['MONSTER'] == E['HATCH3'] + 1
    assert all(E[n] < E['ROCK'] for n in tiles.ELEMS if n not in HANDLER and not n.startswith('SPIRIT')
               and n not in ('DECOR', 'COVER', 'FUNGUS'))
    out.append('FUNGUS_MASK equ %d' % engine.FUNGUS_MASK)
    out += ['        align 256', 'ATOD:', db_lines(atod()), '        align 256', 'NOTETAB:']
    nt = music.notetab()
    for i in range(0, 128, 8):
        out.append('        dw ' + ','.join('%d' % v for v in nt[i:i + 8]))
    names = []
    for n in tiles.ELEMS:
        names.append(HANDLER.get(n, 'h_spirit' if n.startswith('SPIRIT') else 'h_none'))
    names += ['h_none'] * (64 - len(names))
    out += ['        align 256', 'JTAB:', dw_lines(names)]
    pc = [PCLASS.get(n, 0) for n in tiles.ELEMS] + [0] * (64 - len(tiles.ELEMS))
    out += ['PCLASS:', db_lines(pc)]
    rd = [engine.round_dirs(i) for i in range(64)]
    out += ['ROUNDTAB:', db_lines(rd)]
    cn = [CNT.get(n, 0) for n in tiles.ELEMS] + [0] * (64 - len(tiles.ELEMS))
    out += ['CNTCLASS:', db_lines(cn)]
    out += ['DIROFF: dw -1,-%d,1,%d' % (engine.W, engine.W)]
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- looks
def gen_looks():
    looks = {}

    def idx(lk):
        key = tuple(lk)
        if key not in looks:
            looks[key] = len(looks)
        return looks[key]

    idx(tiles.SPACE_L)                       # look 0 = empty
    anim = [0] * 512                         # [phase * 64 + element]
    for e, name in enumerate(tiles.ELEMS):
        seq = tiles.LOOK[name]
        assert len(seq) == 8, name
        for p in range(8):
            anim[p * 64 + e] = idx(seq[p])
    out = ['; generated by build.py - tile looks']
    extra = []
    for k, (nm, seq) in enumerate(tiles.EXTRA.items()):
        out.append('%s equ %d' % (nm, k * 8))
        extra += [idx(lk) for lk in seq]
    thl = []
    for i, th in enumerate(tiles.THEMES):
        tl = tiles.themed_looks(th)
        thl += [idx(tl[k]) for k in tiles.THEMED]
        thl += [0] * (8 - len(tiles.THEMED))
    assert len(looks) <= 256, len(looks)
    pages = [[0] * 256 for _ in range(8)]
    for lk, i in looks.items():
        for q in range(4):
            g, fg, bg = lk[q]
            pages[q * 2][i] = g & 0xFF
            pages[q * 2 + 1][i] = ((g >> 8) << 7) | (fg << 4) | bg
    out += ['NTHEMED equ %d' % len(tiles.THEMED)]
    out += ['THEMED_E: db ' + ','.join('E_%s' % k for k in tiles.THEMED)]
    out += ['        align 256', 'LKTAB:']
    for p in pages:
        out.append(db_lines(p))
    out += ['ANIM:', db_lines(anim), 'ANIMX:', db_lines(extra), 'THEMELK:', db_lines(thl)]
    return '\n'.join(out) + '\n', len(looks)


# ---------------------------------------------------------------- world
def pack(cells):
    """RLE: byte = code | (n-1) << 6 for runs of 1-3, or 0C0h|code, n for 4-255"""
    out = []
    i = 0
    while i < len(cells):
        v = cells[i]
        n = 1
        while i + n < len(cells) and cells[i + n] == v and n < 255:
            n += 1
        if n >= 4:
            out += [0xC0 | v, n]
        else:
            out.append(v | ((n - 1) << 6))
        i += n
    return out


def unpack(data):
    out = []
    i = 0
    while i < len(data):
        b = data[i]
        if b >= 0xC0:
            out += [b & 0x3F] * data[i + 1]
            i += 2
        else:
            out += [b & 0x3F] * ((b >> 6) + 1)
            i += 1
    return out


def gen_world(wd):
    out = ['; generated by build.py - the world', 'NREG equ %d' % len(wd.regions)]
    out.append('START_REGION equ %d' % wd.start_region)
    out.append('START_POS equ %d' % wd.start_pos)
    out.append('REGTAB: dw ' + ','.join('reg_%d' % i for i in range(len(wd.regions))))
    total = 0
    for i, r in enumerate(wd.regions):
        data = pack(r.cells)
        assert unpack(data) == r.cells
        total += len(data)
        out.append('reg_%d:' % i)
        out.append('        db %d' % r.theme)
        out.append('        dw rname_%d, rhint_%d' % (i, i))
        out.append(db_lines(data))
    for i, r in enumerate(wd.regions):
        out.append('rname_%d: %s' % (i, asm_str(r.name)))
        out.append('rhint_%d: %s' % (i, asm_str(r.hint)))
    out.append('NTRANS equ %d' % len(wd.trans))
    out.append('TRANSTAB:')
    for t in wd.trans:
        out.append('        db %d : dw %d : db %d : dw %d' % (t.region, t.pos, t.dregion, t.dpos))
    out.append('NSWITCH equ %d' % len(wd.switches))
    assert len(wd.switches) <= 16
    out.append('SWTAB:')
    for s in wd.switches:
        out.append('        db %d : dw %d : db %d,%d,%d,%d,%d' % (s.region, s.pos, s.target, s.x1, s.y1, s.x2, s.y2))
    g = engine.Game(wd)
    gems, pieces, crowns, mons = g.counts()
    out += ['TOTAL_GEMS equ %d' % gems, 'TOTAL_PIECES equ %d' % pieces, 'TOTAL_CROWNS equ %d' % crowns,
            'TOTAL_MONS equ %d' % mons]
    return '\n'.join(out) + '\n', total, (gems, pieces, crowns, mons)


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w') as f:
            f.write(text)

    wd = world.load()
    write('gen_tables.inc', gen_tables())
    looks, nlooks = gen_looks()
    write('gen_looks.inc', looks)
    wtext, wbytes, totals = gen_world(wd)
    write('gen_world.inc', wtext)
    write('gen_music.inc', music.gen_asm())
    write('gen_logo.inc', logo.gen_asm())
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/skink.sym',
                        '--lst=../build/skink.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'skink.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    print('%s: %d regions (%d bytes packed), %d tile looks, binary %d bytes (%04X-%04X)' % (
        NAME, len(wd.regions), wbytes, nlooks, len(data), LOAD, LOAD + len(data) - 1))
    print('world: %d gems, %d pieces, %d crowns, %d monsters/eggs, %d transporters, %d switches' % (
        totals + (len(wd.trans), len(wd.switches))))


if __name__ == '__main__':
    main()
