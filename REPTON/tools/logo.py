"""logo.py - the SKINK title logo and the Sun Mosaic picture."""
from tiles import BLACK, BLUE, RED, MAGENTA, GREEN, CYAN, YELLOW, WHITE

# ---------------------------------------------------------------- the logo
# 5 x 7 block letters; '#' full block, corners round off with triangles
LETTERS = {
    'S': ['/###\\', '#....', '#....', 'L###\\', '....#', '....#', 'L###J'],
    'K': ['#...#', '#../J', '#./J.', '##...', '#.L\\.', '#..L\\', '#...#'],
    'I': ['.###.', '..#..', '..#..', '..#..', '..#..', '..#..', '.###.'],
    'N': ['#\\..#', '##\\.#', '#L\\.#', '#.L\\#', '#..L#', '#...#', '#...#'],
}
CH = {'#': 0x43, '.': 0x00, '/': 0x4E, '\\': 0x4D, 'L': 0x42, 'J': 0x56}
LOGO_H = 7


def logo_rows(word='SKINK'):
    rows = []
    for y in range(LOGO_H):
        row = []
        for ch in word:
            row += [CH[c] for c in LETTERS[ch][y]] + [0, 0]
        row = row[:-2]
        pad = (40 - len(row)) // 2
        rows.append(([0] * pad + row + [0] * 40)[:40])
    return rows


# ---------------------------------------------------------------- the mosaic
# 12 x 8 cells = 6 x 4 pieces of 2 x 2 cells.  Letters -> (glyph, fg, bg).
MOSAIC = [
    'R..R....R..R',
    '.R..1YY2..R.',
    '...1YYYY2...',
    'RR.YeYYeY.RR',
    'RR.YYYYYY.RR',
    '...3YmmY4...',
    '.R..3YY4..R.',
    'R..R....R..R',
]
MCELL = {
    '.': (0x00, WHITE, BLUE), 'R': (0x6B, YELLOW, BLUE), 'Y': (0x00, WHITE, YELLOW),
    '1': (0x4E, YELLOW, BLUE), '2': (0x4D, YELLOW, BLUE), '3': (0x42, YELLOW, BLUE),
    '4': (0x56, YELLOW, BLUE), 'e': (0x47, BLACK, YELLOW), 'm': (0x3A, RED, YELLOW),
}


def cell_bytes(g, fg, bg):
    return g & 0xFF, ((g >> 8) << 7) | (fg << 4) | bg


def mosaic_tables(npieces):
    """per piece (in reveal order) the 4 cells; reveal order spreads the
    pieces around the picture"""
    pieces = [(px, py) for py in range(4) for px in range(6)]
    order = sorted(range(24), key=lambda i: ((i * 7) % 24))
    pieces = [pieces[i] for i in order]
    chars, attrs = [], []
    for (px, py) in pieces:
        for dy in range(2):
            for dx in range(2):
                c, a = cell_bytes(*MCELL[MOSAIC[py * 2 + dy][px * 2 + dx]])
                chars.append(c)
                attrs.append(a)
    pos = [py * 2 * 40 + px * 2 for (px, py) in pieces]
    return chars, attrs, pos


def gen_asm(npieces=24):
    out = ['; generated by build.py - title logo and the Sun Mosaic', 'LOGO_H equ %d' % LOGO_H, 'LOGO:']
    for r in logo_rows():
        out.append('        db ' + ','.join('%d' % v for v in r))
    chars, attrs, pos = mosaic_tables(npieces)
    out.append('MOS_CH:')
    for i in range(0, len(chars), 16):
        out.append('        db ' + ','.join('%d' % v for v in chars[i:i + 16]))
    out.append('MOS_AT:')
    for i in range(0, len(attrs), 16):
        out.append('        db ' + ','.join('%d' % v for v in attrs[i:i + 16]))
    out.append('MOS_POS:')
    for i in range(0, len(pos), 8):
        out.append('        dw ' + ','.join('%d' % v for v in pos[i:i + 8]))
    return '\n'.join(out) + '\n'
