def warren_rows():
    """the warrens: a perfect maze (a tree, so a spirit following its left
    wall visits every corridor) with plugged cages in dead ends"""
    import random
    rnd = random.Random(7)
    w, h = 29, 15                       # maze area: x 0-28, rows 2-16
    g = [['#'] * w for _ in range(h)]
    cells = [(x, y) for y in range(1, h, 2) for x in range(1, w, 2)]
    seen = {(1, 1)}
    stack = [(1, 1)]
    g[1][1] = ' '
    while stack:
        x, y = stack[-1]
        nb = [(x + dx, y + dy, dx, dy) for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2))
              if 0 < x + dx < w and 0 < y + dy < h and (x + dx, y + dy) not in seen]
        if not nb:
            stack.pop()
            continue
        nx, ny, dx, dy = rnd.choice(nb)
        g[y + dy // 2][x + dx // 2] = ' '
        g[ny][nx] = ' '
        seen.add((nx, ny))
        stack.append((nx, ny))
    dead = [(x, y) for (x, y) in cells
            if sum(g[y + dy][x + dx] == ' ' for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))) == 1]
    dead.sort(key=lambda c: (c[1], c[0]))
    g[0][1] = ' '                       # the way in, from the top
    dead = [d for d in dead if d != (1, 1)]

    def open_nb(x, y):
        return [(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if g[y + dy][x + dx] == ' ']
    # cages in two dead ends, each behind an earth plug
    (px, py), = open_nb(27, 1)          # the cage, behind an earth plug
    g[1][27] = 'C'
    g[py][px] = '.'
    (px, py), = open_nb(5, 5)           # the spirit, behind a barrier
    g[5][5] = '>'
    g[py][px] = '|'
    g[7][19] = '='                      # the switch
    g[11][5] = '+'                      # a mosaic piece
    for x, y in ((3, 1), (11, 1), (1, 5), (11, 13), (9, 3), (23, 13), (15, 5)):
        if g[y][x] == ' ':
            g[y][x] = '*'
    rows = ['1 ' + '.' * 28, '  ' + '.' * 28]
    rows += [''.join(r) + '.' for r in g]
    rows += ['..+.....O.......*.......O.....', '.....*......O.=......*........',
             '...O.........*........O.....2.', '..*......O.......*.......*....', '.' * 30]
    return rows


