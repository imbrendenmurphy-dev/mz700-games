def nice(name):
    return name.replace('_', ' ')


# ---------------------------------------------------------------- rays
def bres(tx, ty):
    n = max(abs(tx), abs(ty))
    return [(round(tx * k / n), round(ty * k / n)) for k in range(1, n + 1)]


OCTS = [(1, 64), (1, -64), (-1, 64), (-1, -64), (64, 1), (64, -1), (-64, 1), (-64, -1)]


def ray_bytes(tx, ty):
    """octant + 16-bit minor-step mask (bit 15 = first step)"""
    cells = bres(tx, ty)
    if abs(tx) >= abs(ty):
        maj = 1 if tx > 0 else -1
        mnr = 64 if ty >= 0 else -64
        prev, mask = 0, 0
        for k, (x, y) in enumerate(cells):
            if y != prev:
                mask |= 1 << (15 - k)
                prev = y
    else:
        maj = 64 if ty > 0 else -64
        mnr = 1 if tx >= 0 else -1
        prev, mask = 0, 0
        for k, (x, y) in enumerate(cells):
            if x != prev:
                mask |= 1 << (15 - k)
                prev = x
    o = OCTS.index((maj, mnr))
    return [o, mask >> 8, mask & 255]


def ray_set(r):
    tg = set()
    for i in range(-r, r + 1):
        tg |= {(i, -r), (i, r), (-r, i), (r, i)}
    out = []
    for t in sorted(tg, key=lambda p: math.atan2(p[1], p[0])):
        out += ray_bytes(*t)
    return len(tg), out


# ---------------------------------------------------------------- data
def gen_data():
    out = ['; generated by build.py - do not edit']
    out.append('        ALIGN 256')
    out.append('ATOD:')
    out += db(atod())
    # tile looks (copied to TLP per zone): glyph, bright glyph, info, colour
    g, gb, info, col = [], [], [], []
    flags, light, amb = [], [], []
    pk = list(defs.PARTICLES)
    for t in defs.TILES:
        name, fl, gg, ggb, mode, c, bg, li, am = t
        assert (gg >> 8) == (ggb >> 8), name
        anim = 0x40 if fl & defs.F_ANIM else 0
        g.append(gg & 255)
        gb.append(ggb & 255)
        info.append(((gg >> 8) << 7) | anim | (mode << 4) | bg)
        col.append(c << 4)
        flags.append(fl)
        light.append(0 if not li else li[0] | (defs.HUE[li[1]] << 4))
        amb.append(0 if not am else pk.index(am) + 1)
    pad = [0] * (64 - len(defs.TILES))
    out.append('        ALIGN 256')
    out.append('TILEDEF:')
    out += db(g + pad) + db(gb + pad) + db(info + pad) + db(col + pad)
    out.append('TDATA:')
    out.append('TFLAGS:')
    out += db(flags + pad)
    out.append('TLIGHT:')
    out += db(light + pad)
    out.append('TAMB:')
    out += db(amb + pad)
    out.append('        ds 64')
    out.append('RAMP:')
    out += db([c << 4 for _, ramp in defs.HUES for c in ramp])
    for i, t in enumerate(defs.TILES):
        out.append('T_%s equ %d' % (t[0], i))
    # themes: wall g, info, col; floor g, gb, info, col; floor2 g, info, col
    out.append('THEMES:')
    tnames = list(defs.THEMES)
    for th in tnames:
        wg, fg, fgb, f2g, wc, fc, f2c, wm = defs.THEMES[th]
        assert (fg >> 8) == (fgb >> 8)
        out += db([wg & 255, ((wg >> 8) << 7) | (wm << 4), wc << 4,
                   fg & 255, fgb & 255, ((fg >> 8) << 7) | (defs.M_LIT << 4), fc << 4,
                   f2g & 255, ((f2g >> 8) << 7) | (defs.M_LIT << 4), f2c << 4])
    # octants: major step, minor step (map deltas)
    out.append('OCTT:')
    for maj, mnr in OCTS:
        out.append('        dw %d,%d' % (maj, mnr))
    # the FOV's rays (radius 16), also the set for static lights of
    # strength 5+ (a light of strength S reaches 2S cells)
    n, rb = ray_set(16)
    out.append('RAYS_16:')
    out.append('        db %d' % n)
    out.append('RAYS16_N equ %d' % n)
    out.append('RAYS16:')
    out += db(rb)
    out.append('RAYSETS:')
    out.append('        dw ' + ','.join('RAYS_%d' % (16 if s > 4 else max(2, 2 * s)) for s in range(9)))
    for r in (2, 4, 6, 8):
        n, rb = ray_set(r)
        out.append('RAYS_%d:' % r)
        out += db([n] + rb)
    # particles: 3 glyphs, 3 attrs, vy, flags (bit 0 gravity, bits 4-5 spread)
    out.append('PKINDS:')
    for name in pk:
        gl, cl, vy, grav, spread = defs.PARTICLES[name]
        out += db([x & 255 for x in gl] + [((x >> 8) << 7) | (c << 4) for x, c in zip(gl, cl)]
                  + [vy, grav | (spread << 4)])
    for i, name in enumerate(pk):
        out.append('P_%s equ %d' % (name, i + 1))
    # monsters: 16 bytes
    out.append('MTYPES:')
    for i, m in enumerate(C.MONSTERS):
        (name, gl, cl, hp, atk, df, spd, ai, fl, xp, li, bolt, dis) = m
        lb = 0 if not li else li[0] | (defs.HUE[li[1]] << 4)
        bb = 0xFF if bolt is None else C.BOLTS[bolt]
        dg = gl if dis is None else dis
        out.append('        db %d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d : dw MN_%s : db 0' % (
            gl & 255, ((gl >> 8) << 7) | (cl << 4), hp, atk, df, spd, C.AI[ai], fl, xp, lb, bb,
            dg & 255, ((dg >> 8) << 7) | ((defs.YELLOW if dis == 0x0C5 else defs.WHITE) << 4), name))
    for i, m in enumerate(C.MONSTERS):
        out.append('M_%s equ %d' % (m[0], i + 1))
        out.append(asm_str('MN_' + m[0], nice(m[0]).capitalize() if m[7] == 'NPC' else nice(m[0]).lower()))
    out.append('NMTYPES equ %d' % len(C.MONSTERS))
    for k, v in C.AI.items():
        out.append('AI_%s equ %d' % (k, v))
    for k, v in C.BOLTS.items():
        out.append('BOLT_%s equ %d' % (k, v))
    # items: 8 bytes
    out.append('ITYPES:')
    for it in C.ITEMS:
        name, gl, cl, kind, val, price = it
        out.append('        db %d,%d,%d,%d,%d : dw IN_%s : db 0' % (
            gl & 255, ((gl >> 8) << 7) | (cl << 4), C.IK[kind], val, price, name))
    for it in C.ITEMS:
        out.append('I_%s equ %d' % (it[0], C.IT[it[0]]))
        out.append(asm_str('IN_' + it[0], ITEM_NAMES.get(it[0], (nice(it[0]) if not it[0].startswith('BOOK_')
                                                                 else 'book of ' + it[0][5:]).lower())))
    for k, v in C.IK.items():
        out.append('IK_%s equ %d' % (k, v))
    out.append('WEAPONS:')
    for w in C.WEAPONS:
        lb = 0 if not w[4] else w[4][0] | (defs.HUE[w[4][1]] << 4)
        out += db([w[1], w[2], w[3], lb])
    out.append('ARMOURS:')
    for a in C.ARMOURS:
        out += db([a[1], a[2]])
    out.append('SPELLS:')
    for i, s in enumerate(C.SPELLS):
        out.append('        db %d : dw SN_%s' % (s[1], s[0]))
    for i, s in enumerate(C.SPELLS):
        out.append('SP_%s equ %d' % (s[0], i))
        out.append(asm_str('SN_' + s[0], s[0]))
    out.append('NSPELLS equ %d' % len(C.SPELLS))
    pnames = list(prefabs.PREFABS)
    # zones: 32 bytes each
    out.append('ZONEDEFS:')
    for z, zd in enumerate(C.ZONES):
        (zname, theme, style, (ltile, lcount), pool, (lo, hi), loot, pfs, links, npc) = zd
        b = [tnames.index(theme), style, defs.T[ltile], lcount]
        b += [C.MON[m] for m in pool] + [lo, hi] + [C.IT[x] for x in loot]
        pf = [0, 0, 0]
        slots = [0] * 9
        for k, (pn, items) in enumerate(pfs):
            pf[k] = pnames.index(pn) + 1
            for j, it in enumerate(items):
                slots[k * 3 + j] = C.IT[it]
        b += pf + slots
        lk = []
        for dest, place in links:
            if place == 'room':
                lk += [dest, 0]
            else:
                lk += [dest, [p for p, _ in pfs].index(place) + 1]
        lk += [0xFF, 0] * (3 - len(links))
        b += lk
        b += [C.MON[npc] if npc else 0]
        assert len(b) == 33, len(b)
        out.append('        db ' + ','.join('%d' % v for v in b) + ' : dw ZN_%d : ds 5' % z)
    for z, zd in enumerate(C.ZONES):
        out.append(asm_str('ZN_%d' % z, zd[0]))
    return '\n'.join(out) + '\n'


def gen_prefabs():
    out = ['; generated by build.py - the prefab rooms (copied to HIDATA)']
    pnames = list(prefabs.PREFABS)
    code = {'#': 'WALL', '.': 'FLOOR', ',': 'FLOOR2', '~': 'WATER', '=': 'LAVA', 'I': 'ICE', 'P': 'PILLAR',
            'B': 'BRAZOFF', 'b': 'BRAZON', 'G': 'GATEP', 'g': 'GATEB', 'M': 'GATEM', 'l': 'GATEL',
            'o': 'GATELO', '^': 'PLATE', 'O': 'BOULDER', 'V': 'LEVER', '/': 'MIRRORA', chr(92): 'MIRRORB',
            'e': 'EMITTER', 't': 'TARGET', 'A': 'ALTAR', 'C': 'CHEST', 'T': 'THRONE', 'c': 'CRYSTAL',
            'F': 'FOUNTAIN', 'f': 'FUNGUS', 'R': 'RUNE', 'K': 'SCONCE', 'D': 'DOOR', 'L': 'LOCKED',
            'S': 'SEAL', '_': 'PEDESTAL', 'Y': 'PEDLIT', 'H': 'LDOOR'}
    mark = {'1': 0xC1, '2': 0xC2, '3': 0xC3, 'm': 0xC8, 'k': 0xC9, 'x': 0xCA}
    out.append('PREFABS:')
    for n in pnames:
        out.append('        dw PF_%s' % n)
    for i, n in enumerate(pnames):
        gr = prefabs.grid(n)
        ex, ey, side = prefabs.entrance(n)
        out.append('PF_%s:' % n)
        out += db([len(gr[0]), len(gr), ex, ey, side])
        cells = []
        for row in gr:
            for ch in row:
                cells.append(mark[ch] if ch in mark else defs.T[code[ch]])
        out += db(cells)
    return chr(10).join(out) + chr(10)


# ---------------------------------------------------------------- output
def mzf(name, load, data, exe):
    hdr = bytearray(128)
    hdr[0] = 0x01
    fn = name.encode('ascii')[:16] + b'\x0d'
    hdr[1:1 + len(fn)] = fn
    for i in range(1 + len(fn), 18):
        hdr[i] = 0x0d
    hdr[18:20] = len(data).to_bytes(2, 'little')
    hdr[20:22] = load.to_bytes(2, 'little')
    hdr[22:24] = exe.to_bytes(2, 'little')
    return bytes(hdr) + data


def main():
    os.makedirs(BUILD, exist_ok=True)
    os.makedirs(REL, exist_ok=True)
    prefabs.check()

    def write(name, text):
        with open(os.path.join(BUILD, name), 'w', newline='\n') as f:
            f.write(text)

    write('gen_data.inc', gen_data())
    write('gen_prefabs.inc', gen_prefabs())
    write('gen_logo.inc', logo.gen_asm())
    write('gen_music.inc', music.gen_asm())
    asm = os.path.join(TOOLS, 'sjasmplus', 'sjasmplus.exe')
    r = subprocess.run([asm, '--nologo', '--msg=war', '--sym=../build/lumen.sym',
                        '--lst=../build/lumen.lst', 'main.asm'],
                       cwd=SRC, capture_output=True, text=True)
    sys.stdout.write(r.stdout + r.stderr)
    if r.returncode:
        sys.exit('assembly failed')
    data = open(os.path.join(BUILD, 'lumen.bin'), 'rb').read()
    out = mzf(NAME, LOAD, data, LOAD)
    for d in (BUILD, REL):
        for ext in ('MZT', 'MZF'):
            with open(os.path.join(d, NAME + '.' + ext), 'wb') as f:
                f.write(out)
    syms = {}
    for line in open(os.path.join(BUILD, 'lumen.sym')):
        p = line.split()
        if len(p) >= 3 and p[1] == 'EQU':
            syms[p[0].rstrip(':')] = int(p[2].replace('0x', ''), 16)
    print('%s: %d bytes; code to %04X (limit 8000), high data to %04X (D000), variables to %04X (AF00)' % (
        NAME, len(data), syms['end_of_code'], syms['hi_end'], syms['vars_end']))


if __name__ == '__main__':
    main()
