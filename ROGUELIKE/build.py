def db(vals, per=16):
    return ['        db ' + ','.join('%d' % (v & 0xFF) for v in vals[i:i + per])
            for i in range(0, len(vals), per)]


def asm_str(label, s):
    s = s.replace('"', "'")
    return '%s: db "%s",0' % (label, s) if label else '        db "%s",0' % s


# ---------------------------------------------------------------- text
ASCII = {' ': 0x00, '!': 0x61, '"': 0x62, '#': 0x63, '$': 0x64, '%': 0x65, '&': 0x66, "'": 0x67,
         '(': 0x68, ')': 0x69, '+': 0x6A, '*': 0x6B, ',': 0x2F, '-': 0x2A, '.': 0x2E, '/': 0x2D,
         ':': 0x4F, ';': 0x2C, '=': 0x2B, '?': 0x49, '<': 0x51, '>': 0x57, '[': 0x52, ']': 0x54,
         '@': 0x55, '_': 0x3C, '^': 0x50, '|': 0x75}


def atod():
    t = [0] * 256
    for c in range(256):
        ch = chr(c)
        if 'A' <= ch <= 'Z':
            t[c] = c - 64
        elif 'a' <= ch <= 'z':
            t[c] = c - 96 + 0x80
        elif '0' <= ch <= '9':
            t[c] = 0x20 + c - 48
        elif ch in ASCII:
            t[c] = ASCII[ch]
        elif c >= 0x80:
            t[c] = c                    # raw display codes pass through
    return t


